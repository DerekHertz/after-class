/**
 * The assembler: several recorded captures become one capture in a new data dir, replayed through the product's own
 * evidence.ingest. Inputs are fabricated here; nothing calls a model.
 */
import { afterEach, describe, expect, test } from "bun:test";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, symlinkSync, unlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { openDb } from "../src/backend/db";
import { createEvidence } from "../src/backend/evidence";
import { sourceIdOf } from "../src/backend/evidence/core";
import type { CaptureFact, CaptureFactBody } from "../src/shared/domain";
import { randomId, stableId } from "../src/shared/ids";
import type { CaptureId, MemoKey } from "../src/shared/ids";
import { media } from "../src/shared/time";
import { ASSEMBLED_JSON, ASSEMBLED_MD, ASSEMBLED_ORIGIN, assembleCaptures, provenanceLine, readProvenance } from "../scripts/assemble-capture";
import { scratchCopy } from "../scripts/probe-export";

const V1 = "aaaaaaaaaaa";
const V2 = "bbbbbbbbbbb";
const V3 = "ccccccccccc";

const cleanup: string[] = [];
afterEach(() => {
  for (const d of cleanup.splice(0)) rmSync(d, { recursive: true, force: true });
});
const tmp = (): string => {
  const d = mkdtempSync(join(tmpdir(), "afterclass-assemble-"));
  cleanup.push(d);
  return d;
};

const jpeg = (tag: number): string => Buffer.from([0xff, 0xd8, 0xff, 0xe0, tag, 2, 3, 4]).toString("base64");

type Clip = { readonly videoId: string; readonly watched: readonly [number, number]; readonly text: string; readonly frameTags: readonly number[]; readonly durationS?: number };

/** A recorded capture on disk: start, then each clip (source, transcript, one span, frames, an ad), then stop. */
function record(clips: readonly Clip[], opts: { readonly wall0?: number; readonly extra?: readonly CaptureFactBody[] } = {}): { readonly dir: string; readonly captureId: string } {
  const dir = tmp();
  const db = openDb(join(dir, "afterclass.sqlite"));
  const keyOf = (input: { readonly after: { readonly frame: { readonly id: string } } }): MemoKey => stableId("key", "frame_change", "t", input.after.frame.id);
  const evidence = createEvidence(db, dir, { lookupFrameChange: (i) => ({ kind: "missing", key: keyOf(i) }), runFrameChange: async () => undefined, frameChangeKey: keyOf, onChange: () => {} });
  const captureId = randomId("cap");
  const bodies: CaptureFactBody[] = [{ kind: "control", action: "start", reason: "user" }];
  for (const [ci, c] of clips.entries()) {
    const [from, to] = c.watched;
    bodies.push(
      { kind: "source", videoId: c.videoId, title: `Clip ${c.videoId}`, channelName: "Prof", url: `https://www.youtube.com/watch?v=${c.videoId}`, durationS: c.durationS ?? 600 },
      { kind: "transcript", videoId: c.videoId, origin: "panel", language: "en", autoGenerated: false, segments: [{ start: media(from + 1), end: media(from + 3), text: c.text }, { start: media(to - 3), end: media(to - 1), text: `${c.text} again` }] },
      { kind: "span", videoId: c.videoId, start: media(from), end: media(to), rate: 1, tabVisible: true, wallDurationMs: (to - from) * 1000 },
      ...c.frameTags.map((tag, n): CaptureFactBody => ({ kind: "frame", videoId: c.videoId, frameId: `f${ci * 10 + n}`, mediaS: media(from + 2 + n * 5), width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: jpeg(tag) })),
      { kind: "ad", videoId: c.videoId, atContentS: media(from + 60), wallDurationMs: 5000, signals: ["dom_class"] },
    );
  }
  bodies.push(...(opts.extra ?? []), { kind: "control", action: "stop", reason: "user" });
  const wall0 = opts.wall0 ?? 1_000_000;
  evidence.ingest({ captureId: captureId as CaptureId, facts: bodies.map((b, i) => ({ captureId: captureId as CaptureId, clientSeq: i, wallMs: wall0 + i * 100, ...b }) as CaptureFact) });
  db.close();
  return { dir, captureId };
}

const sha = (path: string): string => createHash("sha256").update(readFileSync(path)).digest("hex");
function allFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? allFiles(join(dir, e.name)) : [join(dir, e.name)]));
}
const snapshot = (dir: string): Record<string, string> => Object.fromEntries(allFiles(dir).sort().map((f) => [f, sha(f)]));

/** Reads a data dir through a scratch copy, as the other tools do. */
function open(dir: string, captureId: string) {
  const scratch = scratchCopy(dir);
  const db = openDb(scratch.path);
  const keyOf = (i: { readonly after: { readonly frame: { readonly id: string } } }): MemoKey => stableId("key", "frame_change", "t", i.after.frame.id);
  const evidence = createEvidence(db, dir, { lookupFrameChange: (i) => ({ kind: "missing", key: keyOf(i) }), runFrameChange: async () => undefined, frameChangeKey: keyOf, onChange: () => {} });
  const rows = db.sql.query<{ client_seq: number; wall_ms: number; kind: string; body_json: string }, [string]>("SELECT client_seq, wall_ms, kind, body_json FROM capture_facts WHERE capture_id = ? ORDER BY client_seq").all(captureId);
  return {
    bundle: evidence.captureBundle(captureId as CaptureId),
    view: evidence.captureView(captureId as CaptureId),
    rows,
    close: () => {
      db.close();
      rmSync(scratch.dir, { recursive: true, force: true });
    },
  };
}

function twoInputs() {
  const a = record([
    { videoId: V1, watched: [0, 100], text: "alpha one", frameTags: [1, 2] },
    { videoId: V2, watched: [10, 90], text: "alpha two", frameTags: [3] },
  ]);
  const b = record([{ videoId: V3, watched: [20, 140], text: "beta one", frameTags: [1, 9] }], { wall0: 5_000_000 });
  return { a, b };
}

describe("assembleCaptures", () => {
  test("every video keeps its watched intervals, passages and frames; watched seconds add up; frame bytes are the same", () => {
    const { a, b } = twoInputs();
    const out = join(tmp(), "out");
    const done = assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out });
    const asm = open(out, done.captureId);
    const ia = open(a.dir, a.captureId);
    const ib = open(b.dir, b.captureId);
    try {
      for (const [input, vids] of [[ia, [V1, V2]], [ib, [V3]]] as const) {
        for (const v of vids) {
          const pick = (x: typeof asm) => ({
            watched: x.bundle.watched.filter((w) => w.sourceId === sourceIdOf(v)).map((w) => w.intervals),
            passages: x.bundle.passages.filter((p) => p.sourceId === sourceIdOf(v)).map((p) => [p.start, p.end, p.text]),
            frames: x.bundle.frames.filter((f) => f.sourceId === sourceIdOf(v)).map((f) => [f.mediaS, readFileSync(f.file!).toString("hex")]),
          });
          expect(pick(asm)).toEqual(pick(input));
          expect(pick(asm).frames.length).toBeGreaterThan(0);
        }
      }
      expect(asm.bundle.watchedSeconds).toBeCloseTo(ia.bundle.watchedSeconds + ib.bundle.watchedSeconds, 9);
      expect(asm.bundle.watchedSeconds).toBeCloseTo(100 + 80 + 120, 9);
      expect(asm.bundle.frames.length).toBe(5);
      expect(asm.bundle.frames.every((f) => f.file !== null && existsSync(f.file) && f.file.startsWith(out))).toBe(true);
    } finally {
      asm.close();
      ia.close();
      ib.close();
    }
  });

  test("sources follow the order of --in; reversing the inputs reverses the clips", () => {
    const { a, b } = twoInputs();
    const fwd = assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: join(tmp(), "o") });
    expect(fwd.provenance.videoIds).toEqual([V1, V2, V3]);
    const rev = assembleCaptures({ inputs: [{ dataDir: b.dir, captureId: b.captureId }, { dataDir: a.dir, captureId: a.captureId }], outDir: join(tmp(), "o") });
    expect(rev.provenance.videoIds).toEqual([V3, V1, V2]);
    expect(fwd.provenance.joins.map((j) => [j.fromVideoId, j.toVideoId, j.cumulativeWatchedS, j.crossesInputs])).toEqual([[V1, V2, 100, false], [V2, V3, 180, true]]);
    expect(fwd.provenance.inputs.map((i) => i.watchedSeconds)).toEqual([180, 120]);
  });

  test("one start first, one stop last, clientSeq consecutive, wall time shifted with relative timing kept", () => {
    const { a, b } = twoInputs();
    const out = join(tmp(), "out");
    const done = assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out });
    const asm = open(out, done.captureId);
    const ia = open(a.dir, a.captureId);
    const ib = open(b.dir, b.captureId);
    try {
      const controls = asm.rows.filter((r) => r.kind === "control").map((r) => [r.client_seq, JSON.parse(r.body_json).action]);
      expect(controls).toEqual([[0, "start"], [asm.rows.length - 1, "stop"]]);
      expect(asm.rows.map((r) => r.client_seq)).toEqual(asm.rows.map((_, i) => i));
      const inner = (rows: typeof asm.rows) => rows.filter((r) => r.kind !== "control");
      const wallsA = inner(ia.rows).map((r) => r.wall_ms);
      const wallsB = inner(ib.rows).map((r) => r.wall_ms);
      const walls = inner(asm.rows).map((r) => r.wall_ms);
      const mine = [...wallsA, ...wallsB];
      expect(walls.length).toBe(mine.length);
      // relative timing inside each input is unchanged
      const rel = (xs: number[]) => xs.map((x) => x - xs[0]!);
      expect(rel(walls.slice(0, wallsA.length))).toEqual(rel(wallsA));
      expect(rel(walls.slice(wallsA.length))).toEqual(rel(wallsB));
      // and the second input follows the first
      expect(walls[wallsA.length]!).toBeGreaterThan(walls[wallsA.length - 1]!);
      expect(done.provenance.inputs[0]!.wallShiftMs).toBe(0);
      expect(done.provenance.inputs[0]!.droppedControls).toHaveLength(2);
      expect(done.provenance.inputs[1]!.droppedControls).toHaveLength(2);
    } finally {
      asm.close();
      ia.close();
      ib.close();
    }
  });

  test("frames with the same frameId in two inputs both survive on disk", () => {
    const { a, b } = twoInputs(); // both use f1, f2
    const out = join(tmp(), "out");
    const done = assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out });
    expect(done.provenance.inputs[1]!.renamedFrameIds).toBe(2);
    expect(readdirSync(join(out, "frames")).flatMap((d) => readdirSync(join(out, "frames", d)))).toHaveLength(5);
  });

  test("provenance: files, contents, labels and sha256 of every input sqlite", () => {
    const { a, b } = twoInputs();
    const out = join(tmp(), "out");
    const done = assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out, now: () => new Date("2026-11-04T12:00:00Z") });
    const p = readProvenance(out)!;
    expect(p.origin).toBe(ASSEMBLED_ORIGIN);
    expect(p.assembled).toBe(true);
    expect(p.notOneLiveSession).toBe(true);
    expect(p.assembledAt).toBe("2026-11-04T12:00:00.000Z");
    expect(p.captureId).toBe(done.captureId);
    expect(p.inputs.map((i) => [i.dataDir, i.captureId, i.sqliteSha256])).toEqual([
      [a.dir, a.captureId, sha(join(a.dir, "afterclass.sqlite"))],
      [b.dir, b.captureId, sha(join(b.dir, "afterclass.sqlite"))],
    ]);
    const md = readFileSync(join(out, ASSEMBLED_MD), "utf8");
    expect(md).toContain("ASSEMBLED");
    expect(md).toContain("NOT one live session");
    expect(md).toContain(ASSEMBLED_ORIGIN);
    expect(md).toContain("2026-11-04");
    for (const i of p.inputs) {
      expect(md).toContain(i.dataDir);
      expect(md).toContain(i.captureId);
      expect(md).toContain(i.sqliteSha256);
    }
    expect(provenanceLine(p)).toContain(ASSEMBLED_ORIGIN);
    expect(JSON.parse(readFileSync(join(out, ASSEMBLED_JSON), "utf8")).captureId).toBe(done.captureId);
    expect(readProvenance(a.dir)).toBeNull();
  });

  test("the inputs are byte-identical afterwards", () => {
    const { a, b } = twoInputs();
    const before = { ...snapshot(a.dir), ...snapshot(b.dir) };
    assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: join(tmp(), "out") });
    expect({ ...snapshot(a.dir), ...snapshot(b.dir) }).toEqual(before);
  });

  test("refuses --out inside an input dir, through a symlink, through .., or equal to it", () => {
    const { a, b } = twoInputs();
    const inputs = [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }];
    expect(() => assembleCaptures({ inputs, outDir: join(a.dir, "assembled") })).toThrow("inside the input data dir");
    expect(() => assembleCaptures({ inputs, outDir: join(b.dir, "x", "..", "x", "y") })).toThrow("inside the input data dir");
    const elsewhere = tmp();
    mkdirSync(join(a.dir, "sub"));
    symlinkSync(join(a.dir, "sub"), join(elsewhere, "link"));
    expect(() => assembleCaptures({ inputs, outDir: join(elsewhere, "link", "out") })).toThrow("inside the input data dir");
    expect(() => assembleCaptures({ inputs, outDir: join(elsewhere, "link") })).toThrow("inside the input data dir");
    expect(() => assembleCaptures({ inputs, outDir: join(elsewhere, "x", "..", "link", "z") })).toThrow("inside the input data dir");
    expect(() => assembleCaptures({ inputs, outDir: a.dir })).toThrow("inside the input data dir");
    expect(existsSync(join(a.dir, "assembled"))).toBe(false);
  });

  test("refuses a non-empty --out and leaves it alone", () => {
    const { a, b } = twoInputs();
    const out = tmp();
    writeFileSync(join(out, "keep.txt"), "mine");
    expect(() => assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out })).toThrow("not empty");
    expect(readdirSync(out)).toEqual(["keep.txt"]);
  });

  test("an empty existing --out is fine", () => {
    const { a } = twoInputs();
    expect(assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }], outDir: tmp() }).provenance.videoIds).toEqual([V1, V2]);
  });

  test("a video in two inputs with different facts is refused, with nothing written", () => {
    const a = record([{ videoId: V1, watched: [0, 100], text: "same video", frameTags: [1] }]);
    const b = record([{ videoId: V1, watched: [0, 60], text: "same video", frameTags: [1] }]);
    const out = join(tmp(), "out");
    expect(() => assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out })).toThrow(`video ${V1} appears in input 1`);
    expect(existsSync(out)).toBe(false);
  });

  test("a video in two inputs with identical facts is taken once, from the first input", () => {
    const clip: Clip = { videoId: V1, watched: [0, 100], text: "same video", frameTags: [1] };
    const a = record([clip]);
    const b = record([clip, { videoId: V2, watched: [0, 50], text: "other", frameTags: [] }], { wall0: 9_000_000 });
    const done = assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: join(tmp(), "out") });
    expect(done.provenance.videoIds).toEqual([V1, V2]);
    expect(done.provenance.watchedSeconds).toBeCloseTo(150, 9);
    expect(done.provenance.inputs[1]!.videosDeduped).toEqual([V1]);
  });

  test("a tampered input (a frame file removed) is refused with a clear error and nothing is left behind", () => {
    const { a, b } = twoInputs();
    const victim = allFiles(join(a.dir, "frames"))[0]!;
    unlinkSync(victim);
    const out = join(tmp(), "out");
    expect(() => assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out })).toThrow("is missing");
    expect(existsSync(out)).toBe(false);
  });

  test("an unknown capture id is refused", () => {
    const { a } = twoInputs();
    expect(() => assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: "cap_nope" }], outDir: join(tmp(), "out") })).toThrow("has no facts");
  });

  test("the same input twice is refused", () => {
    const { a } = twoInputs();
    expect(() => assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: a.dir, captureId: a.captureId }], outDir: join(tmp(), "out") })).toThrow("twice");
  });

  test("a capture left paused is caught by the comparison, not silently assembled", () => {
    // Input A ends paused (no resume): B's spans would fall outside capture in the assembled stream.
    const a = record([{ videoId: V1, watched: [0, 100], text: "x", frameTags: [] }], { extra: [{ kind: "control", action: "pause", reason: "user" }] });
    const b = record([{ videoId: V2, watched: [0, 100], text: "y", frameTags: [] }]);
    const out = join(tmp(), "out");
    expect(() => assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }, { dataDir: b.dir, captureId: b.captureId }], outDir: out })).toThrow("verification failed");
    expect(existsSync(out)).toBe(false);
  });

  test("outBytes is the size of every file in the out dir", () => {
    const { a } = twoInputs();
    const out = join(tmp(), "out");
    const done = assembleCaptures({ inputs: [{ dataDir: a.dir, captureId: a.captureId }], outDir: out });
    expect(done.outBytes).toBe(allFiles(out).reduce((s, f) => s + statSync(f).size, 0));
  });
});
