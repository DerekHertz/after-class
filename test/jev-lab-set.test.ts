describe("schema 1 label files score exactly as before Amendment 1", () => {
  test("a two-lecture schema 1 run reproduces the tune and score reports of the pre-amendment lab line for line", async () => {
    const o = labRun(V1_CLIPS, v1Labels);
    const tune = await runLab({ ...o.base(), phase: "tune" });
    expect(normalize(tune.report.text)).toBe(V1_TUNE_REPORT);
    const score = await runLab({ ...o.base(), phase: "score" });
    expect(normalize(score.report.text)).toBe(V1_SCORE_REPORT);
    expect(normalize(reportFromFile(score.resultsPath, o.files).text)).toBe(V1_SCORE_REPORT);
  });

  test("a schema 1 label in the first window of the held-out half still counts (and is missed); only sets exclude it", async () => {
    const o = labRun(V1_CLIPS, v1Labels);
    await runLab({ ...o.base(), phase: "tune" });
    const score = await runLab({ ...o.base(), phase: "score" });
    expect(score.report.text).toContain("0/1 detected; missed at 100s");
    expect(score.report.text).not.toContain("no model could detect");
  });

  test("results written before Amendment 1 (no videoId on windows, frames or judgments) rescore to the same report", async () => {
    const o = labRun(V1_CLIPS, v1Labels);
    await runLab({ ...o.base(), phase: "tune" });
    const score = await runLab({ ...o.base(), phase: "score" });
    const rows = readFileSync(score.resultsPath, "utf8").split("\n").filter((l) => l !== "").map((l) => JSON.parse(l) as Record<string, unknown>);
    for (const row of rows) {
      if (row.t === "judgment") delete row.videoId;
      if (row.t === "lecture") for (const x of [...(row.windows as Record<string, unknown>[]), ...(row.frames as Record<string, unknown>[])]) delete x.videoId;
    }
    writeFileSync(score.resultsPath, rows.map((r) => JSON.stringify(r)).join("\n") + "\n");
    expect(readFileSync(score.resultsPath, "utf8")).not.toContain('"videoId":"bbbbbbbbbbb","purpose"');
    expect(reportFromFile(score.resultsPath, o.files).text).toBe(score.report.text);
  });
});
