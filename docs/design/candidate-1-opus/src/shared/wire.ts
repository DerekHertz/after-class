/** Streamed to the review app as NDJSON lines. `say_delta` lets speech start on the first sentence. */
export type TutorStreamEvent =
  | { type: "learner_turn_stored"; turnId: string }
  | { type: "say_delta"; text: string }
  | { type: "sentence"; text: string }
  | { type: "turn_complete"; turnId: string; moveKind: string; evidence: readonly string[] }
  | { type: "turn_failed"; error: string; retryable: boolean };
