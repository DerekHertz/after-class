describe("parseProposal", () => {
  const forbidden = { titles: ["Hash Tables", "Introduction"], videoIds: ["aaaaaaaaaaa"] };
  const ok = (text: string) => parseProposal(text, forbidden);
  const reason = (text: string) => {
    const r = ok(text);
    return r.ok ? "" : r.error;
  };

  test("one JSON object, one code fence allowed; rationale plus a body that passes validateArmConfig", () => {
    expect(ok(proposalJson()).ok).toBe(true);
    expect(ok("```json\n" + proposalJson() + "\n```").ok).toBe(true);
    expect(reason("here you go: " + proposalJson())).toMatch(/not valid JSON/);
    expect(reason("```json\n" + proposalJson() + "\n```\n```json\n{}\n```")).toMatch(/not valid JSON/);
    expect(reason("[1]")).toMatch(/one JSON object/);
  });

  test("requires a non-empty rationale string; an unknown key, a wrong kind or an out-of-range value is refused by the arm validator", () => {
    expect(reason(proposalJson({ rationale: "" }))).toMatch(/rationale/);
    expect(reason(proposalJson({ rationale: 3 }))).toMatch(/rationale/);
    expect(reason(JSON.stringify({ ...JSON.parse(proposalJson()), rationale: undefined }))).toMatch(/rationale/);
    expect(reason(proposalJson({ model: "other" }))).toMatch(/model is not allowed/);
    expect(reason(proposalJson({ routing: {} }))).toMatch(/routing is not allowed/);
    expect(reason(proposalJson({ thresholds: { yesAtOrAbove: 0.2, noAtOrBelow: 0.5 } }))).toMatch(/thresholds out of range/);
    expect(reason(proposalJson({ questions: { newConcept: "x".repeat(601), stoppingPoint: "a?", teachingChange: "b?" } }))).toMatch(/at most 600/);
  });

  test("refuses question wording that names a clip title, a videoId or a mm:ss time; the rationale may", () => {
    const q = (newConcept: string) => proposalJson({ questions: { newConcept, stoppingPoint: "Pause?", teachingChange: "Change?" } });
    expect(reason(q("Is this about Hash Tables?"))).toMatch(/clip title "Hash Tables"/);
    expect(reason(q("Is this clip aaaaaaaaaaa?"))).toMatch(/clip id/);
    expect(reason(q("Is this after 12:30?"))).toMatch(/mm:ss/);
    expect(reason(q("Is this after 1:02:30?"))).toMatch(/mm:ss/);
    expect(ok(q("Does the lecturer introduce a new subject in the passage?")).ok).toBe(true);
    expect(ok(q("Is the ratio 3:1 or 10:1 here?")).ok).toBe(true);
    expect(ok(proposalJson({ rationale: "At 12:30 the p was high in Hash Tables." })).ok).toBe(true);
  });
});

