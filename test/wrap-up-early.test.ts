/**
 * #234: the review's end starts the wrap-up summary while the tutor's closing line streams, and the save joins that call.
 * Every boot is `main` on a temp dir with port 0 and fake tasks gated by the test. No test makes a live call.
 */
import { afterEach, describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { Provider, Purpose } from "../src/shared/domain";
import type { CaptureId, IdPart } from "../src/shared/ids";
import { stableId } from "../src/shared/ids";
import { main } from "../src/backend/main";
import type { Running, TaskSet } from "../src/backend/main";
import { wrapUpInput } from "../src/backend/review/tutor";
import { canonicalInterpretation, canonicalResourceSearch, canonicalRevision } from "../src/backend/preparation/tasks";
import { deferred, fakeTask, ok } from "./fakes";
import type { FakeStep, FakeTask } from "./fakes";

const CAP = stableId("cap", "wrap-up-early") as CaptureId;
const VIDEO = "dQw4w9WgXcQ";

const scratch: string[] = [];
const running: Running[] = [];
afterEach(async () => {
  for (const r of running.splice(0)) await r.stop();
  for (const d of scratch.splice(0)) rmSync(d, { recursive: true, force: true });
});

const dir = (prefix: string) => {
  const d = mkdtempSync(join(tmpdir(), prefix));
  scratch.push(d);
  return d;
};

const until = async (done: () => boolean, ms = 10_000) => {
  const end = Date.now() + ms;
  while (!done()) {
    if (Date.now() > end) throw new Error("timed out waiting");
    await Bun.sleep(20);
  }
};

const FACTS = [
  { kind: "control", action: "start", reason: "user" },
  { kind: "source", videoId: VIDEO, title: "Lecture", channelName: "Prof", url: `https://www.youtube.com/watch?v=${VIDEO}`, durationS: 600 },
  { kind: "transcript", videoId: VIDEO, origin: "panel", language: "en", autoGenerated: false, segments: Array.from({ length: 10 }, (_, i) => ({ start: i * 10, end: i * 10 + 10, text: `Statement ${i + 1} about the topic.` })) },
  { kind: "span", videoId: VIDEO, start: 0, end: 100, rate: 1, tabVisible: true, wallDurationMs: 100_000 },
  { kind: "control", action: "stop", reason: "user" },
].map((f, clientSeq) => ({ ...f, clientSeq, wallMs: 1000 + clientSeq }));

function scripted<I, O>(purpose: Purpose, provider: Provider, canonical: (i: I) => IdPart, answer: (input: I) => FakeStep<O> | Promise<FakeStep<O>>): FakeTask<I, O> {
  const t = fakeTask<IdPart, O>({ purpose, provider, maxAttempts: 1, answer: (i) => answer(i as unknown as I) });
  return Object.assign(t, { canonicalInput: canonical }) as unknown as FakeTask<I, O>;
}

/** Preparation that finishes at once with one supported claim, so a review can start. */
function preparationTasks() {
  const boundary = scripted("boundary", "jev", (i: any) => ({ window: i.window.id, new: i.newPassages.map((p: any) => p.id) }), () => ok({ boundary: false } as never));
  const frameChange = scripted("frame_change", "jev", () => "frame", () => ok({ verdict: "yes" as const, p: 0.9 }));
  const interpret = scripted("interpretation", "claude", canonicalInterpretation as never, (i: any) =>
    ok({ concepts: [{ label: "Topic", summary: "What the lecture is about", claims: [{ text: "The lecture states its topic first.", evidence: [i.newMaterial.passages[0].id], visualDependent: false, assumptions: [] }], confusions: [] }], links: [], supersedes: [] }));
  const revise = scripted("claim_revision", "claude", canonicalRevision as never, () => ok(null as never));
  const checkClaim = scripted("claim_check", "jev", (i: any) => ({ claim: i.claim.text, passages: i.passages.map((p: any) => p.id) }), () => ok({ verdict: "yes" as const, p: 0.9 }));
  const searchResources = scripted("resource_search", "claude", canonicalResourceSearch as never, () => ok([] as never));
  return { boundary, frameChange, preparation: { interpret, revise, checkClaim, searchResources } };
}

type Summary = { observations: never[]; notes: never[] };

/** A review whose tutor's closing line and summary call each wait on a gate the test opens, and whose end turn is already on its way. */
async function gatedEnd(summaryOutcomes: readonly ("ok" | "fail")[] = ["ok"]) {
  const closingLine = deferred<void>();
  const summary = deferred<void>();
  let spoken = false;
  let calls = 0;
  const wrapUp = scripted<unknown, Summary>("wrap_up", "claude", () => "wrap-gated", async () => {
    const outcome = summaryOutcomes[Math.min(calls++, summaryOutcomes.length - 1)]!;
    await summary.promise;
    return outcome === "fail" ? { kind: "error", message: "claude timed out", retryable: false, usage: null, deltas: [] } : ok({ observations: [], notes: [] });
  });
  const tutor = scripted("tutor_turn", "claude", () => "tutor", async () => {
    await closingLine.promise;
    return ok({ move: { kind: "wrap_up" }, say: "That is the end of this review." });
  });
  const tasks = { ...preparationTasks(), tutor, wrapUp } as unknown as TaskSet;
  const configDir = dir("afterclass-config-");
  const env = { AFTERCLASS_DATA: dir("afterclass-data-"), AFTERCLASS_MODE: "replay" };
  const boot = async () => {
    const r = await main({ port: 0, buildApp: false, configDir, log: () => {}, error: () => {}, tasks, env });
    running.push(r);
    return r;
  };
  let r = await boot();
  const base = () => `http://127.0.0.1:${r.port}`;
  const headers = () => ({ Authorization: `Bearer ${r.token}`, "Content-Type": "application/json" });
  const post = (path: string, body: unknown = {}) => fetch(`${base()}${path}`, { method: "POST", headers: headers(), body: JSON.stringify(body) }).then(async (res) => ({ status: res.status, body: (await res.json()) as Record<string, any> }));
  expect((await fetch(`${base()}/ingest`, { method: "POST", headers: headers(), body: JSON.stringify({ captureId: CAP, facts: FACTS }) })).status).toBe(200);
  expect((await post(`/captures/${CAP}/invite`, { answer: "wait" })).status).toBe(200);
  await until(() => r.modules.segmentation.current(CAP).some((c) => r.modules.preparation.prep(c.id).finished));
  const reviewId = stableId("rvw", "wrap-up-early");
  expect((await post(`/captures/${CAP}/reviews`, { reviewId, choice: "prepared_only" })).body.kind).toBe("started");
  const ending = fetch(`${base()}/reviews/${reviewId}/turns`, { method: "POST", headers: headers(), body: JSON.stringify({ turnId: stableId("turn", "wrap-up-early"), act: { kind: "end" } }) }).then((res) => res.text());
  return {
    get r() { return r; },
    reviewId, wrapUp, ending,
    wasSpoken: () => spoken,
    speak: () => ((spoken = true), closingLine.resolve()),
    finishSummary: () => summary.resolve(),
    save: () => post(`/reviews/${reviewId}/save`),
    async restart() {
      await r.stop();
      running.splice(running.indexOf(r), 1);
      r = await boot();
    },
  };
}

describe("the end starts the wrap-up summary (#234)", () => {
  test("the summary call starts while the closing line is still being written, and the save joins that one call", async () => {
    const t = await gatedEnd();
    await until(() => t.wrapUp.calls.length === 1);
    expect(t.wasSpoken()).toBe(false);
    t.speak();
    expect(await t.ending).toContain("turn_complete");

    let answered = false;
    const saving = t.save().then((res) => ((answered = true), res));
    await Bun.sleep(150);
    expect(answered).toBe(false);
    t.finishSummary();
    expect((await saving).body).toEqual({ kind: "saved", notes: 0, observations: 0, links: 0 });
    expect(t.wrapUp.calls).toHaveLength(1);
  }, 30_000);

  test("a save after the summary call finished answers without a second call", async () => {
    const t = await gatedEnd();
    await until(() => t.wrapUp.calls.length === 1);
    t.finishSummary();
    t.speak();
    expect(await t.ending).toContain("turn_complete");
    await Bun.sleep(100);
    expect((await t.save()).body).toMatchObject({ kind: "saved" });
    expect(t.wrapUp.calls).toHaveLength(1);
  }, 30_000);

  test("the summary reads the turns without the closing line, so the call that started early is the call the save needs", async () => {
    const t = await gatedEnd();
    await until(() => t.wrapUp.calls.length === 1);
    t.speak();
    await t.ending;
    const turns = t.r.modules.reviews.view(t.reviewId).turns;
    expect(turns.at(-1)).toMatchObject({ actor: "tutor", move: { kind: "wrap_up" } });
    expect(wrapUpInput(turns, []).turns).toEqual(turns.slice(0, -1));
    expect((t.wrapUp.calls[0] as { turns: readonly unknown[] }).turns).toHaveLength(turns.length - 1);
    t.finishSummary();
  }, 30_000);

  test("a save after the early call failed asks once more instead of reporting that failure", async () => {
    const t = await gatedEnd(["fail", "ok"]);
    await until(() => t.wrapUp.calls.length === 1);
    t.speak();
    await t.ending;
    t.finishSummary();
    await Bun.sleep(100);
    expect((await t.save()).body).toEqual({ kind: "saved", notes: 0, observations: 0, links: 0 });
    expect(t.wrapUp.calls).toHaveLength(2);
  }, 30_000);

  test("a restart between the failed early call and the first save changes nothing: that save asks once more, and a failure it gets is retried by the next", async () => {
    const t = await gatedEnd(["fail", "fail", "ok"]);
    await until(() => t.wrapUp.calls.length === 1);
    t.speak();
    await t.ending;
    t.finishSummary();
    await Bun.sleep(100);
    await t.restart();
    expect((await t.save()).body).toMatchObject({ kind: "save_failed", retryable: true });
    expect(t.wrapUp.calls).toHaveLength(2);
    expect((await t.save()).body).toEqual({ kind: "saved", notes: 0, observations: 0, links: 0 });
    expect(t.wrapUp.calls).toHaveLength(3);
  }, 30_000);

  test("a save that joins the early call while it runs reports that call's failure, and the retry asks once more", async () => {
    const t = await gatedEnd(["fail", "ok"]);
    await until(() => t.wrapUp.calls.length === 1);
    t.speak();
    await t.ending;
    const saving = t.save();
    await Bun.sleep(150);
    t.finishSummary();
    expect((await saving).body).toMatchObject({ kind: "save_failed", retryable: true });
    expect(t.wrapUp.calls).toHaveLength(1);
    expect((await t.save()).body).toEqual({ kind: "saved", notes: 0, observations: 0, links: 0 });
    expect(t.wrapUp.calls).toHaveLength(2);
  }, 30_000);
});
