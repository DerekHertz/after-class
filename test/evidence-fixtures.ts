const cleanup: string[] = [];

/** Scripted frame-change answers keyed by the `after` frame id. A frame with no entry is unjudged. */
type Script = Map<EvidenceId, Lookup<Verdict>>;

export function harness(opts: { clock?: { t: number } } = {}) {
  const dir = mkdtempSync(join(tmpdir(), "afterclass-evidence-"));
  cleanup.push(dir);
  const db = testDb();
  const script: Script = new Map();
  const changes = { n: 0 };
  const clock = opts.clock ?? { t: 1_000_000 };
  const evidence = createEvidence(db, dir, {
    lookupFrameChange: (input) => script.get(input.after.frame.id) ?? { kind: "missing", key: keyOf(input) },
    runFrameChange: async () => undefined,
    frameChangeKey: keyOf,
    onChange: () => void changes.n++,
    now: () => clock.t,
  });
  return { db, dir, evidence, script, changes, clock };
}

export const keyOf = (input: FrameChangeInput): MemoKey => stableId("key", "frame_change", input.before?.frame.id ?? null, input.after.frame.id);

export const hit = (value: Verdict, id: EvidenceId): Lookup<Verdict> => ({ kind: "hit", key: stableId("key", id), value, atSeq: asSeq(1) });

/** Builds a fact stream with consecutive clientSeqs. */
export function stream(captureId: CaptureId = randomId("cap")) {
  let next = 0;
  const facts: CaptureFact[] = [];
  const push = (body: CaptureFactBody): CaptureFact => {
    const fact = { captureId, clientSeq: next++, wallMs: 1000 + next, ...body } as CaptureFact;
    facts.push(fact);
    return fact;
  };
  const span = (start: number, end: number, o: { video?: string; rate?: number; visible?: boolean; wallMs?: number } = {}) =>
    push({
      kind: "span", videoId: o.video ?? VIDEO, start: media(start), end: media(end), rate: o.rate ?? 1,
      tabVisible: o.visible ?? true, wallDurationMs: o.wallMs ?? (end - start) * 1000,
    });
  return {
    captureId, facts, push, span,
    control: (action: "start" | "pause" | "resume" | "stop", reason: "user" | "left_watch_page" = "user") => push({ kind: "control", action, reason }),
    source: (o: { video?: string; durationS?: number | null } = {}) =>
      push({ kind: "source", videoId: o.video ?? VIDEO, title: "Lecture", channelName: "Prof", url: "https://www.youtube.com/watch?v=x", durationS: o.durationS === undefined ? 600 : o.durationS }),
    transcript: (segments: readonly [number, number, string][], o: { video?: string; origin?: "panel" | "asr" } = {}) =>
      push({
        kind: "transcript", videoId: o.video ?? VIDEO, origin: o.origin ?? "panel", language: "en", autoGenerated: false,
        segments: segments.map(([s, e, text]) => ({ start: media(s), end: media(e), text })),
      }),
    ad: (atContentS: number, wallDurationMs = 15_000) => push({ kind: "ad", videoId: VIDEO, atContentS: media(atContentS), wallDurationMs, signals: ["dom_class"] }),
    frame: (frameId: string, mediaS: number, o: { video?: string; jpeg?: string } = {}) =>
      push({
        kind: "frame", videoId: o.video ?? VIDEO, frameId, mediaS: media(mediaS), width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: o.jpeg ?? JPEG,
      }),
  };
}

/** A stream with no frame samples is one long frame stall; tests about other gaps look past it. */
export const exceptStalls = <G extends { readonly reason: string }>(gaps: readonly G[]) => gaps.filter((g) => g.reason !== "frame_stall");

export const textsOf = (passages: readonly { readonly text: string }[]) => passages.map((p) => p.text);

export const count = (h: ReturnType<typeof harness>, table: string) => h.db.sql.query<{ n: number }, []>(`SELECT COUNT(*) AS n FROM ${table}`).get()!.n;

export function registerCleanup() {
  afterEach(() => {
    for (const d of cleanup.splice(0)) rmSync(d, { recursive: true, force: true });
  });
}
