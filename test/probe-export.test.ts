/**
 * The capture probe's exporter: which capture it exports when none is named.
 * Real regression: a second Start after a Stop made a tiny capture, and the
 * "newest capture" default exported that one ("has no evidence") while the
 * 10-minute run sat unseen.
 */
import { describe, expect, test } from "bun:test";
import { join } from "node:path";
import { ensureLocalUser, openDb, scopeDb } from "../src/backend/db";
import { createEvidence } from "../src/backend/evidence";
import { randomId, stableId } from "../src/shared/ids";
import type { CaptureId, MemoKey } from "../src/shared/ids";
import type { CaptureFact, CaptureFactBody } from "../src/shared/domain";
import { media } from "../src/shared/time";
import { exportCapture, pickCapture } from "../scripts/probe-export";
import { tmpDir } from "./tmp";

const VIDEO = "aaaaaaaaaaa";
const JPEG = Buffer.from([0xff, 0xd8, 0xff, 0xe0, 1, 2, 3, 4]).toString("base64");

describe("pickCapture", () => {
  const c = (captureId: string, watchedSeconds: number, hasEvidence = true) => ({ captureId, watchedSeconds, hasEvidence });

  test("takes the capture with the most watched time, not the newest (candidates are newest first)", () => {
    expect(pickCapture([c("new-tiny", 3), c("old-long", 600)])).toBe("old-long");
  });

  test("a tie goes to the newest", () => {
    expect(pickCapture([c("newer", 60), c("older", 60)])).toBe("newer");
  });

  test("ignores a capture with no evidence even if it reports watched time", () => {
    expect(pickCapture([c("empty", 900, false), c("real", 5)])).toBe("real");
  });

  test("returns undefined when nothing has evidence or there are no captures", () => {
    expect(pickCapture([c("a", 0, false)])).toBeUndefined();
    expect(pickCapture([])).toBeUndefined();
  });
});

describe("exportCapture default capture", () => {
  function twoCaptures() {
    const dir = tmpDir("afterclass-probe-export-");
    const raw = openDb(join(dir, "afterclass.sqlite"));
    const db = scopeDb(raw, ensureLocalUser(raw));
    const keyOf = (input: { readonly after: { readonly frame: { readonly id: string } } }): MemoKey => stableId("key", "frame_change", input.after.frame.id);
    const evidence = createEvidence(db, dir, {
      lookupFrameChange: (input) => ({ kind: "missing", key: keyOf(input) }),
      runFrameChange: async () => undefined,
      frameChangeKey: keyOf,
      onChange: () => {},
    });
    const facts = (captureId: CaptureId, bodies: readonly CaptureFactBody[]): readonly CaptureFact[] => bodies.map((b, i) => ({ captureId, clientSeq: i, wallMs: 1000 + i, ...b }) as CaptureFact);
    const source: CaptureFactBody = { kind: "source", videoId: VIDEO, title: "Lecture", channelName: "Prof", url: "https://www.youtube.com/watch?v=x", durationS: 600 };
    const transcript: CaptureFactBody = { kind: "transcript", videoId: VIDEO, origin: "panel", language: "en", autoGenerated: false, segments: [{ start: media(2), end: media(4), text: "inside" }] };

    const real = randomId("cap");
    evidence.ingest({
      captureId: real,
      facts: facts(real, [
        { kind: "control", action: "start", reason: "user" },
        source,
        transcript,
        { kind: "span", videoId: VIDEO, start: media(0), end: media(120), rate: 1, tabVisible: true, wallDurationMs: 120_000 },
        { kind: "frame", videoId: VIDEO, frameId: "f1", mediaS: media(10), width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: JPEG },
        { kind: "control", action: "stop", reason: "user" },
      ]),
    });
    // Started again after the stop, ingested last (so it has the highest seq): the "newest" capture.
    const tiny = randomId("cap");
    evidence.ingest({ captureId: tiny, facts: facts(tiny, [{ kind: "control", action: "start", reason: "user" }, source, transcript, { kind: "control", action: "stop", reason: "user" }]) });
    db.close();
    return { dir, real, tiny };
  }

  test("exports the long capture, not the newer empty one, and says what it skipped", () => {
    const { dir, real, tiny } = twoCaptures();
    const done = exportCapture({ dataDir: dir, outDir: join(dir, "out") });
    expect(done.captureId).toBe(real);
    expect(done.notes.join("\n")).toContain(tiny);
    expect(done.notes.join("\n")).toContain("--capture");
  });

  test("an explicit capture id still wins, and an empty one still fails loudly", () => {
    const { dir, real, tiny } = twoCaptures();
    expect(exportCapture({ dataDir: dir, outDir: join(dir, "out"), captureId: real }).captureId).toBe(real);
    expect(() => exportCapture({ dataDir: dir, outDir: join(dir, "out2"), captureId: tiny })).toThrow("has no evidence");
  });
});
