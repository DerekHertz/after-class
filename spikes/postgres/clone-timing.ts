import { SQL } from "bun";
import { freshDatabase, ADMIN_URL, urlFor } from "./pg";
import { openPgDb } from "./kernel-pg";
import { pgMigrations } from "./translate";
const f = await freshDatabase("spike_tpl2");
const m = pgMigrations(true);
const t0 = performance.now();
const d = await openPgDb(f.url, m, { max: 1 });
await d.close();
console.log("migrate empty db:", Math.round(performance.now() - t0), "ms");
const admin = new SQL({ url: ADMIN_URL, max: 1 });
const t1 = performance.now();
for (let i = 0; i < 20; i++) await admin.unsafe(`CREATE DATABASE spike_c${i} TEMPLATE spike_tpl2`);
console.log("CREATE DATABASE TEMPLATE x20:", Math.round((performance.now() - t1) / 20), "ms each");
const t2 = performance.now();
const clones = await Promise.all(Array.from({ length: 20 }, (_, i) => openPgDb(urlFor(`spike_c${i}`), m, { max: 1 })));
console.log("open + verify migrations on a clone:", Math.round((performance.now() - t2) / 20), "ms each (parallel x20)");
for (const c of clones) await c.close();
const sch = new SQL({ url: f.url, max: 1 });
const t3 = performance.now();
for (let i = 0; i < 20; i++) await sch.begin(async (t) => { await t`INSERT INTO seq_counter SELECT 2, 0 WHERE false`; });
console.log("trivial begin/commit x20:", Math.round((performance.now() - t3) / 20), "ms each");
await sch.close();
for (let i = 0; i < 20; i++) await admin.unsafe(`DROP DATABASE spike_c${i} WITH (FORCE)`);
await admin.unsafe("DROP DATABASE spike_tpl2 WITH (FORCE)");
await admin.close();
process.exit(0);
