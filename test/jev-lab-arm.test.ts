// ───────────────────────────── wording as an input ─────────────────────────────

describe("question wording as an input", () => {
  test("omitted or the product's wording keeps version 1; any other wording is arm-<16 hex> and differs per text", () => {
    expect(boundaryWordingVersion()).toBe("1");
    expect(frameChangeWordingVersion()).toBe("1");
    expect(boundaryWordingVersion({ newConcept: PRODUCT_QUESTIONS.newConcept, stoppingPoint: PRODUCT_QUESTIONS.stoppingPoint })).toBe("1");
    const a = boundaryWordingVersion({ newConcept: "x", stoppingPoint: "y" });
    expect(a).toMatch(/^arm-[0-9a-f]{16}$/);
    expect(boundaryWordingVersion({ newConcept: "x", stoppingPoint: "z" })).not.toBe(a);
    expect(frameChangeWordingVersion({ teachingChange: "q" })).toMatch(/^arm-[0-9a-f]{16}$/);
  });

  test("the task takes the wording into the request and into its version; without it the product's task is unchanged", () => {
    const jev: JevClient = { ask: () => Promise.reject(new Error("no call")) };
    expect(boundaryTask(jev).version).toBe(boundaryTask(jev, { newConcept: PRODUCT_QUESTIONS.newConcept, stoppingPoint: PRODUCT_QUESTIONS.stoppingPoint }).version);
    expect(boundaryTask(jev).version).toBe("boundary.1@0.7/0.3");
    expect(frameChangeTask(jev).version).toBe("frame_change.1@0.7/0.3");
    expect(boundaryTask(jev, { newConcept: "x", stoppingPoint: "y" }).version).toMatch(/^boundary\.arm-[0-9a-f]{16}@/);
  });

  test("changed wording is sent, is never served a judgment made with other wording, and the product's wording keeps key and version", async () => {
    const o = lab();
    const client = scripted();
    const cfg = productConfig();
    const r1 = await runLab({ ...o.base(client), phase: "tune", arm: "a", armConfig: cfg });
    expect(r1.newCalls).toBe(7);
    const j1 = parseResults(readFileSync(r1.resultsPath, "utf8")).judgments;
    expect(j1.every((j) => j.questionVersion === "1")).toBe(true);

    const changed = withWording(cfg, "Alpha");
    const r2 = await runLab({ ...o.base(client), phase: "tune", arm: "a", armConfig: changed });
    expect(r2.newCalls).toBe(7);
    const j2 = parseResults(readFileSync(r2.resultsPath, "utf8")).judgments;
    expect(j2.every((j) => !j.reused && /^arm-[0-9a-f]{16}$/.test(j.questionVersion))).toBe(true);
    expect(new Set([...j1, ...j2].map((j) => j.key)).size).toBe(14);
    const sentNew = client.requests.filter((r) => "new_concept" in r.questions).slice(-1)[0]!;
    expect((sentNew.questions.new_concept as { instructions: string }).instructions).toBe("Alpha new concept?");

    // the same wording again reuses its own judgments, and product wording again reuses the first round's
    const r3 = await runLab({ ...o.base(client), phase: "tune", arm: "a", armConfig: changed });
    expect(r3.newCalls).toBe(0);
    expect(parseResults(readFileSync(r3.resultsPath, "utf8")).judgments.every((j) => j.reused)).toBe(true);
  });

  test("a product-wording arm shares keys with experiment 2 and prints no Questions block; experiment 2's header and report carry nothing new", async () => {
    const o = lab();
    const e2 = await runLab({ ...o.base(), phase: "tune" });
    const e2Parsed = parseResults(readFileSync(e2.resultsPath, "utf8"));
    expect(Object.keys(e2Parsed.header)).toEqual(["t", "version", "runId", "phase", "round", "origin", "model", "config", "thresholds"]);
    expect(e2.report.text).not.toContain("Questions");
    expect(e2.report.text).not.toContain("Arm:");
    expect(reportFromFile(e2.resultsPath, o.base().labelFiles).text).toBe(e2.report.text);

    const arm = await runLab({ ...o.base(), phase: "tune", arm: "p", armConfig: productConfig() });
    expect(parseResults(readFileSync(arm.resultsPath, "utf8")).judgments.map((j) => j.key)).toEqual(e2Parsed.judgments.map((j) => j.key));
    expect(arm.report.text).not.toContain("Questions");
    expect(arm.report.text).toContain("[fixture] Arm: p");
  });

  test("changed wording is recorded in the results header and printed once as a Questions block, and a rescore reproduces it", async () => {
    const o = lab();
    const cfg = withWording(productConfig(), "Beta");
    const r = await runLab({ ...o.base(), phase: "tune", arm: "b", armConfig: cfg });
    expect(parseResults(readFileSync(r.resultsPath, "utf8")).header.questions).toEqual(cfg.questions);
    expect(r.report.text).toContain('[fixture]   newConcept: "Beta new concept?"');
    expect(r.report.text.match(/Questions \(/g)).toHaveLength(1);
    expect(reportFromFile(r.resultsPath, o.base().labelFiles).text).toBe(r.report.text);
    for (const line of r.report.text.split("\n")) if (line !== "") expect(line.startsWith("[fixture] ")).toBe(true);
  });
});

