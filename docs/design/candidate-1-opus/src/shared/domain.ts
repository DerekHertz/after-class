// ───────────────────────────── Usage (R17) ──────────────────────────────────

/**
 * Cost has no default. "unknown" carries no number at all, so unknown can
 * never be summed as zero. Totals are computed per kind.
 */
export type Cost =
  | { kind: "measured"; usd: number }
  | { kind: "notional"; usd: number; basis: "claude_subscription" }
  | { kind: "estimated"; usd: number; basis: string }
  | { kind: "unknown"; reason: string };

export type Purpose =
  | "boundary" | "frame_change" | "claim_check" | "interpretation" | "claim_revision"
  | "resource_search" | "tutor_turn" | "wrap_up";

export type UsageEvent = {
  readonly id: UsageEventId; // stableId("use", memoKey, attemptNo) — retry of a write is a no-op
  readonly provider: "jev" | "claude";
  readonly model: string;
  readonly purpose: Purpose;
  readonly memoKey: MemoKey;
  readonly attemptNo: number;
  readonly outcome: "ok" | "error" | "aborted";
  readonly inputTokens: number | null;
  readonly outputTokens: number | null;
  readonly cacheReadTokens: number | null;
  readonly cost: Cost;
  readonly startedAtMs: number;
  readonly durationMs: number;
};

export type UsageSummary = {
  readonly byKind: Readonly<Record<Cost["kind"], { calls: number; usd: number | null }>>;
  readonly byPurpose: Readonly<Record<Purpose, { calls: number; errors: number; unknownCost: number }>>;
};
