function dir(prefix: string): string {
  const d = mkdtempSync(join(tmpdir(), prefix));
  scratch.push(d);
  return d;
}

type Boot = { readonly r: Running; readonly logs: string[]; readonly errors: string[]; readonly configDir: string; readonly dataDir: string; readonly base: string };

async function boot(options: MainOptions = {}, env: Record<string, string | undefined> = {}): Promise<Boot> {
  const configDir = options.configDir ?? dir("afterclass-config-");
  const dataDir = dir("afterclass-data-");
  const logs: string[] = [];
  const errors: string[] = [];
  const r = await main({
    port: 0, buildApp: false, configDir, log: (t) => void logs.push(t), error: (t) => void errors.push(t),
    ...options, env: { AFTERCLASS_DATA: dataDir, ...env },
  });
  running.push(r);
  return { r, logs, errors, configDir, dataDir, base: `http://127.0.0.1:${r.port}` };
}

const until = async (done: () => boolean, ms = 10_000): Promise<void> => {
  const end = Date.now() + ms;
  while (!done()) {
    if (Date.now() > end) throw new Error("timed out waiting");
    await Bun.sleep(20);
  }
};

// ───────────────────────────── a fixture capture ─────────────────────────────

/** Control start, source, a transcript of ten 10 s segments, one 100 s span, optionally two frames, then stop. */
function fixture(o: { frames: boolean }): Record<string, unknown>[] {
  const body: Record<string, unknown>[] = [
    { kind: "control", action: "start", reason: "user" },
    { kind: "source", videoId: VIDEO, title: "Lecture", channelName: "Prof", url: `https://www.youtube.com/watch?v=${VIDEO}`, durationS: 600 },
    {
      kind: "transcript", videoId: VIDEO, origin: "panel", language: "en", autoGenerated: false,
      segments: Array.from({ length: 10 }, (_, i) => ({ start: i * 10, end: i * 10 + 10, text: `Statement ${i + 1} about the topic.` })),
    },
    { kind: "span", videoId: VIDEO, start: 0, end: 100, rate: 1, tabVisible: true, wallDurationMs: 100_000 },
    ...(o.frames
      ? [5, 50].map((mediaS, i) => ({
          kind: "frame", videoId: VIDEO, frameId: `f${i}`, mediaS, width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: JPEG.toString("base64"),
        }))
      : []),
    { kind: "control", action: "stop", reason: "user" },
  ];
  return body.map((f, clientSeq) => ({ ...f, clientSeq, wallMs: 1000 + clientSeq }));
}

const authed = (token: string) => ({ Authorization: `Bearer ${token}`, "Content-Type": "application/json" });

async function ingest(b: Boot, facts: unknown[]) {
  const res = await fetch(`${b.base}/ingest`, { method: "POST", headers: authed(b.r.token), body: JSON.stringify({ captureId: CAP, facts }) });
  expect(res.status).toBe(200);
  return ingestAckResponse.parse(await res.json());
}

// ───────────────────────────── fake tasks ─────────────────────────────

function scripted<I, O>(purpose: Purpose, provider: Provider, canonical: (i: I) => IdPart, answer: (input: I) => FakeStep<O> | Promise<FakeStep<O>>): FakeTask<I, O> {
  const t = fakeTask<IdPart, O>({ purpose, provider, maxAttempts: 1, answer: (i) => answer(i as unknown as I) });
  return Object.assign(t, { canonicalInput: canonical }) as unknown as FakeTask<I, O>;
}

function fakeTasks() {
  const frameBytesSeen: number[] = [];
  const boundary = scripted<BoundaryInput, ReturnType<typeof judged>>("boundary", "jev",
    (i) => ({ window: i.window.id, new: i.newPassages.map((p) => p.id), context: i.contextPassages.map((p) => p.id), frames: i.frames.map((f) => f.frame.id) }),
    (i) => ok(judged(i.window.id)));
  const frameChange = scripted<FrameChangeInput, "yes">("frame_change", "jev",
    (i) => ({ before: i.before?.frame.id ?? null, after: i.after.frame.id, nearby: i.nearbyPassages.map((p) => p.id) }),
    () => ok("yes" as const));
  const interpret = scripted<InterpretationInput, InterpretationOutput>("interpretation", "claude", canonicalInterpretation, (i) => {
    const drafts: ClaimDraft[] = [
      { text: "The lecture states its topic first.", evidence: [i.newMaterial.passages[0]!.id], visualDependent: false, assumptions: [] },
      ...i.newMaterial.frames.slice(0, 1).map((f): ClaimDraft => ({ text: "The first slide shows the topic.", evidence: [f.id], visualDependent: true, assumptions: [] })),
    ];
    return ok({ concepts: [{ label: "Topic", summary: "What the lecture is about", claims: drafts, confusions: [] }], links: [], supersedes: [] });
  });
  const revise = scripted("claim_revision", "claude", canonicalRevision, () => fail("no revision expected"));
  const checkClaim = scripted<ClaimSupportInput, { verdict: "yes"; p: number }>("claim_check", "jev",
    (i) => ({ claim: { text: i.claim.text, evidence: [...i.claim.evidence], visualDependent: i.claim.visualDependent, assumptions: [...i.claim.assumptions] }, passages: i.passages.map((p) => p.id), frames: i.frames.map((f) => f.frame.id) }),
    (i) => {
      for (const f of i.frames) frameBytesSeen.push(f.bytes().length);
      return ok({ verdict: "yes" as const, p: 0.9 });
    });
  const searchResources = scripted("resource_search", "claude", canonicalResourceSearch, () => ok([]));
  const tutor = scripted("tutor_turn", "claude", () => "tutor", () => fail("no tutor turn in this test"));
  const wrapUp = scripted("wrap_up", "claude", () => "wrap", () => fail("no wrap-up in this test"));
  const tasks = { boundary, frameChange, preparation: { interpret, revise, checkClaim, searchResources }, tutor, wrapUp } as unknown as TaskSet;
  return { tasks, boundary, frameChange, interpret, checkClaim, frameBytesSeen };
}

const judged = (windowId: WindowId) => ({
  windowId, newConcept: "no" as const, stoppingPoint: "no" as const, pNewConcept: 0.1, pStoppingPoint: 0.1, questionVersion: "fake",
});

