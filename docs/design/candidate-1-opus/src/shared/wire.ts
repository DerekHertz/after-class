/**
 * Wire schemas (zod 4). The ONLY place JSON from another process is trusted
 * into domain types. Routes call `parse*`; nothing past a route sees `unknown`.
 * Domain modules never import this file (boundary-discipline).
 *
 * Extension ↔ backend:
 *   POST /ingest      { captureId, facts: WireFact[] }  →  IngestAck
 * App ↔ backend: see API below. Tutor turns stream NDJSON TutorStreamEvent.
 */
import { z } from "zod";
import type { CaptureFact, InviteState, LearnerAct } from "./domain";

const mediaS = z.number().finite().nonnegative();

const factBody = z.discriminatedUnion("kind", [
  z.object({ kind: z.literal("control"), action: z.enum(["start", "pause", "resume", "stop"]), reason: z.enum(["user", "left_watch_page", "returned_to_watch_page", "tab_closed"]) }),
  z.object({ kind: z.literal("source"), videoId: z.string().regex(/^[\w-]{11}$/), title: z.string(), channelName: z.string(), url: z.url(), durationS: z.number().nullable() }),
  z.object({
    kind: z.literal("transcript"), videoId: z.string(), origin: z.enum(["panel", "caption_intercept", "asr"]),
    language: z.string(), autoGenerated: z.boolean(),
    segments: z.array(z.object({ start: mediaS, end: mediaS, text: z.string() })).max(20_000),
  }),
  z.object({ kind: z.literal("transcript_unavailable"), videoId: z.string(), reason: z.enum(["no_captions", "panel_missing", "unusable", "intercept_failed"]) }),
  z.object({ kind: z.literal("span"), videoId: z.string(), start: mediaS, end: mediaS, rate: z.number().positive().max(16), tabVisible: z.boolean() })
    .refine((s) => s.end > s.start, "span end must exceed start"),
  z.object({ kind: z.literal("ad"), videoId: z.string(), atContentS: mediaS, wallDurationMs: z.number().int().nonnegative() }),
  z.object({
    kind: z.literal("frame"), videoId: z.string(), frameId: z.string().max(64), mediaS,
    width: z.number().int().min(280).max(1568), height: z.number().int().min(280).max(1568), // Jev bounds enforced at capture
    trigger: z.enum(["change_settled", "keyframe", "first"]), diff: z.number(), jpegBase64: z.string().max(16 * 1024 * 1024),
  }),
  z.object({ kind: z.literal("channel"), channel: z.enum(["transcript", "frames", "playback"]), health: z.enum(["ok", "failed", "stalled"]), videoId: z.string().nullable(), atMediaS: mediaS.nullable(), detail: z.string().max(500) }),
  z.object({ kind: z.literal("transcription_choice"), videoId: z.string(), choice: z.enum(["accept_asr", "continue_with_gap"]) }),
]);

export const ingestBatch = z.object({
  captureId: z.string(),
  facts: z.array(z.intersection(z.object({ clientSeq: z.number().int().nonnegative(), wallMs: z.number() }), factBody)).max(500),
});

/** Backend → extension, piggybacked on every ingest response (no push channel needed in the MV3 worker). */
export type IngestAck = {
  readonly ackedThroughSeq: number; // highest contiguous clientSeq stored
  readonly invite: InviteState;
  readonly capture: { readonly transcript: string; readonly frames: string; readonly reviewAppUrl: string };
};

