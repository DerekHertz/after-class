type Harness = Awaited<ReturnType<typeof harness>>;
/** A data dir, signed labels, experiment 2's baseline (one tune round and its held-out scoring, scripted Jev) and a place for proposals. */
async function harness() {
  const { dir: dataDir, captureId } = makeCapture();
  const labDir = tmp("lab");
  const propDir = join(labDir, "propose");
  mkdirSync(propDir, { recursive: true });
  const labelFile = writeLabels(tmp("labels"), captureId);
  let t = 0;
  const run = (over: Partial<RunOptions> & { phase: "tune" | "score" }): Promise<{ resultsPath: string; reportPath: string }> =>
    runLab({ dataDir, labDir, labelFiles: [labelFile], live: false, client: scriptedJev(), now: () => (t += 5), retryDelayMs: () => 0, out: () => {}, ...over });
  const base = await run({ phase: "tune" });
  const score = await run({ phase: "score" });
  return { dataDir, labDir, propDir, labelFile, captureId, run, baseTune: base.resultsPath, baseScoreReport: score.reportPath, baseState: join(labDir, "fixture", "state.json") };
}
