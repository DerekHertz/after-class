const jpeg = (tag: number) => Buffer.from([0xff, 0xd8, 0xff, 0xc0, 0x00, 0x11, 0x08, 0x01, 0x68, 0x02, 0x80, 0, 0, 0, 0, 0, 0, 0, 0, tag]);

type Frm = { id: string; at: number };
type ClipSpec = { videoId: string; len: number; frames: Frm[] };
const every = (prefix: string, step: number, first: number, count: number): Frm[] => Array.from({ length: count }, (_, i) => ({ id: `${prefix}${i + 1}`, at: first + i * step }));

/** A: 100 s, 5 frames (1 call). B: 60 s, 30 frames (2 calls: 24, then 9 with 3 repeated). C: 30 s, no frames (1 text-only call). */
const CLIPS: ClipSpec[] = [
  { videoId: A, len: 100, frames: every("a", 20, 10, 5) },
  { videoId: B, len: 60, frames: every("b", 2, 1, 30) },
  { videoId: C, len: 30, frames: [] },
];

function makeCapture(clips: readonly ClipSpec[], opts: { assembled?: boolean } = {}): { dir: string; captureId: CaptureId } {
  const dir = tmp("capture");
  const db = openDb(join(dir, "afterclass.sqlite"));
  const keyOf = (input: { readonly after: { readonly frame: { readonly id: string } } }): MemoKey => stableId("key", "frame_change", "test", input.after.frame.id);
  const evidence = createEvidence(db, dir, { lookupFrameChange: (i) => ({ kind: "missing", key: keyOf(i) }), runFrameChange: async () => undefined, frameChangeKey: keyOf, onChange: () => {} });
  const captureId = randomId("cap");
  const bodies: CaptureFactBody[] = [{ kind: "control", action: "start", reason: "user" }];
  for (const c of clips) {
    const segments = [];
    for (let t = 0; t < c.len; t += 10) segments.push({ start: media(t), end: media(Math.min(c.len, t + 10)), text: `lecture ${c.videoId} at ${t}` });
    bodies.push(
      { kind: "source", videoId: c.videoId, title: `Clip ${c.videoId[0]}`, channelName: "Prof", url: `https://www.youtube.com/watch?v=${c.videoId}`, durationS: c.len },
      { kind: "transcript", videoId: c.videoId, origin: "panel", language: "en", autoGenerated: false, segments },
      { kind: "span", videoId: c.videoId, start: media(0), end: media(c.len), rate: 1, tabVisible: true, wallDurationMs: c.len * 1000 },
      ...c.frames.map((f, i): CaptureFactBody => ({ kind: "frame", videoId: c.videoId, frameId: f.id, mediaS: media(f.at), width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: jpeg(i + 1).toString("base64") })),
    );
  }
  bodies.push({ kind: "control", action: "stop", reason: "user" });
  evidence.ingest({ captureId, facts: bodies.map((b, i) => ({ captureId, clientSeq: i, wallMs: 1000 + i, ...b }) as CaptureFact) });
  db.close();
  if (opts.assembled) {
    writeFileSync(join(dir, "ASSEMBLED.json"), JSON.stringify({ assembled: true, origin: "assembled (replayed live data)", captureId, assembledAt: "2026-11-04T00:00:00.000Z", inputs: [{ dataDir: "/inputs/one", captureId: "cap_in1" }, { dataDir: "/inputs/two", captureId: "cap_in2" }] }));
  }
  return { dir, captureId };
}

/** Path to path-digest of every file under a dir: byte-identical means this is unchanged. */
function digest(dir: string): string {
  const lines: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else lines.push(`${p.slice(dir.length)} ${createHash("sha256").update(readFileSync(p)).digest("hex")}`);
    }
  };
  walk(dir);
  return lines.join("\n");
}

// ───────────────────────────── a scripted Claude client ─────────────────────────────

const usage = { model: "claude-opus-5-5", inputTokens: 10, outputTokens: 5, cacheReadTokens: null, cost: { kind: "unknown", reason: "fake" } } as const;
type Responder = (req: ClaudeRequest, n: number) => string | Error;

function fakeClient(respond: Responder): { client: ClaudeCli; requests: ClaudeRequest[] } {
  const requests: ClaudeRequest[] = [];
  const client: ClaudeCli = {
    async structured() {
      throw new Error("the proposal tool must not use structured()");
    },
    async streamText(req) {
      requests.push(req);
      const r = respond(req, requests.length);
      if (r instanceof Error) throw r;
      return { text: r, usage };
    },
  };
  return { client, requests };
}

const spanIn = (prompt: string) => {
  const m = /Watched span: ([\d.]+) s to ([\d.]+) s/.exec(prompt)!;
  return { start: Number(m[1]), end: Number(m[2]) };
};
const framesIn = (req: ClaudeRequest) =>
  req.images.map((i) => {
    const m = /^frame (\S+) at ([\d.]+) s/.exec(i.label)!;
    return { id: m[1]!, t: Number(m[2]) };
  });

/** A valid answer built from what the request shows: a boundary at the middle, a step at the second frame, the first two frames as duplicates. */
const goodText = (req: ClaudeRequest): string => {
  const s = spanIn(req.prompt);
  const f = framesIn(req);
  return JSON.stringify({
    boundaries: [{ mediaS: (s.start + s.end) / 2, reason: "The topic changes here." }],
    visualSteps: f.length > 1 ? [{ mediaS: f[1]!.t, reason: "New slide text." }] : [],
    duplicateGroups: f.length > 1 ? [{ frames: [{ frameId: f[0]!.id, mediaS: f[0]!.t }, { frameId: f[1]!.id, mediaS: f[1]!.t }], reason: "Same slide." }] : [],
  });
};
const good: Responder = (req) => goodText(req);

