describe("main, replay mode with fake tasks", () => {
  test("a posted capture is segmented, judged, interpreted and checked into usable claims, then read back", async () => {
    const fakes = fakeTasks();
    const appDir = join(dir("afterclass-app-"), "app");
    const b = await boot({ tasks: fakes.tasks, buildApp: true, appDir }, { AFTERCLASS_MODE: "replay" });
    const { modules } = b.r;

    const ack = await ingest(b, fixture({ frames: true }));
    expect(ack.ackedThroughSeq).toBe(6);
    expect(ack.reviewAppUrl).toBe(`${b.base}/app/capture/${CAP}`);

    await until(() => modules.segmentation.current(CAP).some((c) => modules.preparation.prep(c.id).finished));
    const chunks = modules.segmentation.current(CAP);
    expect(chunks).toHaveLength(1);

    const claims = modules.preparation.assessableIn(CAP, chunks[0]!.material);
    expect(claims.map((c) => c.text).sort()).toEqual(["The first slide shows the topic.", "The lecture states its topic first."]);
    // frameBytes reached the claim check: the cited frame's JPEG came off evidence's disk
    expect(fakes.frameBytesSeen).toEqual([JPEG.length]);
    // the first frame has no previous frame, so only the second one was judged
    expect(fakes.frameChange.calls).toHaveLength(1);
    expect(fakes.interpret.calls).toHaveLength(1);

    // read it back over HTTP: the capture, the usage ledger, the review app
    const view = captureResponse.parse(await (await fetch(`${b.base}/captures/${CAP}`, { headers: authed(b.r.token) })).json());
    expect(view.capture.status.state).toBe("stopped");
    expect(view.capture.watchedSeconds).toBe(100);
    const usage = (await (await fetch(`${b.base}/usage`, { headers: authed(b.r.token) })).json()) as { byPurpose: Record<string, { calls: number }> };
    expect(usage.byPurpose.interpretation!.calls).toBe(1);
    expect(usage.byPurpose.claim_check!.calls).toBe(2);
    expect(usage.byPurpose.frame_change!.calls).toBe(1);

    const options = modules.reviews.options(CAP);
    expect(options.kind).toBe("ready");
    if (options.kind === "ready") expect(options.scope.supportedClaims).toBe(2);

    const html = await (await fetch(`${b.base}/app/`)).text();
    expect(html).toContain(`<meta name="afterclass-token" content="${b.r.token}">`);
    expect(existsSync(join(appDir, "index.html"))).toBe(true);
  }, 30_000);

  test("a restart resumes: the stored capture is preparing again without a new post", async () => {
    const fakes = fakeTasks();
    const configDir = dir("afterclass-config-");
    const dataDir = dir("afterclass-data-");
    const env = { AFTERCLASS_DATA: dataDir, AFTERCLASS_MODE: "replay" };
    const first = await boot({ tasks: fakes.tasks, configDir }, env);
    await ingest(first, fixture({ frames: false }));
    await until(() => first.r.modules.segmentation.current(CAP).some((c) => first.r.modules.preparation.prep(c.id).finished));
    await first.r.stop();
    running.splice(running.indexOf(first.r), 1);

    const second = await boot({ tasks: fakes.tasks, configDir }, env);
    expect(second.r.modules.segmentation.current(CAP)).toHaveLength(1);
    expect(second.r.modules.preparation.assessableIn(CAP, second.r.modules.segmentation.current(CAP)[0]!.material)).toHaveLength(1);
  }, 30_000);
});

// ───────────────────────────── M7b: the record, preparation and segmentation reach the server ─────────────────────────────

describe("main, the live backend serves save, retry-preparation, the record and evidence", () => {
  const wrapUpScript = (failFirst: number) => {
    let calls = 0;
    return scripted<unknown, { observations: never[]; notes: never[] }>("wrap_up", "claude", () => `wrap-${Math.min(calls, 1)}`, () => {
      calls += 1;
      return calls <= failFirst ? fail("claude timed out") : ok({ observations: [], notes: [] });
    });
  };

  const json = async (r: Response) => ({ status: r.status, body: (await r.json()) as Record<string, any> });
  const get = (b: Boot, path: string) => fetch(`${b.base}${path}`, { headers: authed(b.r.token) }).then(json);
  const post = (b: Boot, path: string, body: unknown = {}) => fetch(`${b.base}${path}`, { method: "POST", headers: authed(b.r.token), body: JSON.stringify(body) }).then(json);

  test("save and retry-preparation answer instead of 501; a failed save reads save_pending across a restart, and retrying it twice saves one record (R15)", async () => {
    const fakes = fakeTasks();
    const wrapUp = wrapUpScript(1);
    const tutor = scripted("tutor_turn", "claude", () => "tutor", () => ok({ move: { kind: "wrap_up" }, say: "That is the end of this review." }));
    const tasks = { ...fakes.tasks, wrapUp, tutor } as unknown as TaskSet;
    const configDir = dir("afterclass-config-");
    const env = { AFTERCLASS_DATA: dir("afterclass-data-"), AFTERCLASS_MODE: "replay" };
    const first = await boot({ tasks, configDir }, env);
    await ingest(first, fixture({ frames: false }));
    await until(() => first.r.modules.segmentation.current(CAP).some((c) => first.r.modules.preparation.prep(c.id).finished));

    // retry-preparation: nothing is stuck, so nothing is re-queued, but the route is wired
    const retry = await fetch(`${first.base}/captures/${CAP}/retry-preparation`, { method: "POST", headers: authed(first.r.token) });
    expect(retry.status).toBe(204);
    expect((await post(first, `/reviews/${stableId("rvw", "none")}/save`)).status).toBe(404);

    const reviewId = stableId("rvw", "main-test-review");
    const started = await post(first, `/captures/${CAP}/reviews`, { reviewId, choice: "prepared_only" });
    expect(started.body.kind).toBe("started");
    expect((await get(first, `/reviews/${reviewId}`)).body.saved).toBe("unsaved");

    // a review must have ended before it can be saved: the learner ends it, and with no model the code wraps it up
    expect((await post(first, `/reviews/${reviewId}/save`)).status).toBe(409);
    const ending = await fetch(`${first.base}/reviews/${reviewId}/turns`, { method: "POST", headers: authed(first.r.token), body: JSON.stringify({ turnId: stableId("turn", "main-test-end"), act: { kind: "end" } }) });
    expect(ending.status).toBe(200);
    expect(await ending.text()).toContain("turn_complete");
    expect((await get(first, `/reviews/${reviewId}`)).body.state.phase).toBe("ended");
    // #138: ending records a pending save before any POST /save, so a closed tab cannot leave it without a row.
    expect((await get(first, `/reviews/${reviewId}`)).body.saved).toBe("save_pending");

    expect((await post(first, `/reviews/${reviewId}/save`)).body).toMatchObject({ kind: "save_failed", retryable: true });
    expect((await get(first, `/reviews/${reviewId}`)).body.saved).toBe("save_pending");

    await first.r.stop();
    running.splice(running.indexOf(first.r), 1);
    const second = await boot({ tasks, configDir }, env);
    expect((await get(second, `/reviews/${reviewId}`)).body.saved).toBe("save_pending");

    const once = await post(second, `/reviews/${reviewId}/save`);
    const twice = await post(second, `/reviews/${reviewId}/save`);
    expect(once.body).toEqual({ kind: "saved", notes: 0, observations: 0, links: 0 });
    expect(twice.body).toEqual(once.body);
    expect((await get(second, `/reviews/${reviewId}`)).body.saved).toBe("saved");
    expect(second.r.modules.db.sql.query("SELECT COUNT(*) AS n FROM saved_reviews").get()).toEqual({ n: 1 });
    expect((await get(second, `/record?reviewId=${reviewId}`)).status).toBe(200);
  }, 30_000);

  test("the evidence routes answer from the real store: lookup, a frame image, and a delete", async () => {
    const fakes = fakeTasks();
    const b = await boot({ tasks: fakes.tasks }, { AFTERCLASS_MODE: "replay" });
    await ingest(b, fixture({ frames: true }));
    const bundle = await get(b, `/evidence?captureId=${CAP}`);
    expect(bundle.status).toBe(200);
    expect(bundle.body.passages.length).toBe(10);
    const frame = bundle.body.frames[0] as { id: string };
    const image = await fetch(`${b.base}/frames/${frame.id}`, { headers: authed(b.r.token) });
    expect(image.status).toBe(200);
    expect(Buffer.from(await image.arrayBuffer())).toEqual(JPEG);

    const gone = await fetch(`${b.base}/record/evidence/delete`, { method: "POST", headers: authed(b.r.token), body: JSON.stringify({ evidenceIds: [frame.id] }) });
    expect(gone.status).toBe(204);
    expect((await fetch(`${b.base}/frames/${frame.id}`, { headers: authed(b.r.token) })).status).toBe(404);
  }, 30_000);
});

