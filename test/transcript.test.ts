const oldRow = (ts: string, text: string) => `
  <ytd-transcript-segment-renderer class="style-scope ytd-transcript-segment-list-renderer" active>
    <div class="segment style-scope ytd-transcript-segment-renderer" role="button" tabindex="0" aria-label="${ts} ${text}">
      <div class="segment-start-offset style-scope ytd-transcript-segment-renderer" tabindex="-1" aria-hidden="true">
        <div class="segment-timestamp style-scope ytd-transcript-segment-renderer">
          ${ts}
        </div>
      </div>
      <yt-formatted-string class="segment-text style-scope ytd-transcript-segment-renderer" strip-text="">${text}</yt-formatted-string>
    </div>
  </ytd-transcript-segment-renderer>`;

const newRow = (ts: string, text: string) => `
  <transcript-segment-view-model class="ytwTranscriptSegmentViewModelHost">
    <div class="ytwTranscriptSegmentViewModelTimestamp">${ts}</div>
    <div class="ytwTranscriptSegmentViewModelTimestampA11yLabel">${ts} seconds</div>
    <span class="yt-core-attributed-string yt-core-attributed-string--white-space-pre-wrap" role="text">${text}</span>
  </transcript-segment-view-model>`;

const footer = (label: string) => `
  <ytd-transcript-footer-renderer class="style-scope">
    <yt-dropdown-menu><tp-yt-paper-menu-button><div id="label-container"><yt-formatted-string id="label-text" class="style-scope">${label}</yt-formatted-string></div></tp-yt-paper-menu-button></yt-dropdown-menu>
  </ytd-transcript-footer-renderer>`;

const panel = (rows: string[], label = "English (auto-generated)") =>
  `<ytd-engagement-panel-section-list-renderer target-id="engagement-panel-searchable-transcript"><div id="body">${rows.join("")}</div>${footer(label)}</ytd-engagement-panel-section-list-renderer>`;

const seg = (start: number, end: number, text: string): TranscriptSegment => ({ start: media(start), end: media(end), text });

describe("clock and text parsing", () => {
  test.each([
    ["0:05", 5],
    ["2:05", 125],
    ["1:02:03", 3723],
    ["12", 12],
    [" 10:00 ", 600],
  ])("parseClock(%j) is %p", (input, expected) => {
    expect(parseClock(input)).toBe(expected);
  });

  test.each(["", "abc", "1:2", "1:60:00:00", "-3"])("parseClock(%j) is null", (input) => {
    expect(parseClock(input)).toBeNull();
  });

  test("entities and whitespace are normalised, tags dropped", () => {
    expect(decodeEntities("it&#39;s &amp; &lt;b&gt; &#x41;&nbsp;&bogus;")).toBe("it's & <b> A &bogus;");
    expect(normalizeText("  so\n  <span>the</span>   matrix&nbsp;A ")).toBe("so the matrix A");
  });

  test("language labels split out the auto-generated marker", () => {
    expect(parseLanguageLabel("English (auto-generated)")).toEqual({ language: "English", autoGenerated: true });
    expect(parseLanguageLabel("English")).toEqual({ language: "English", autoGenerated: false });
    expect(parseLanguageLabel("")).toEqual({ language: "unknown", autoGenerated: false });
  });
});

describe("transcript panel rows", () => {
  test("old markup: timestamps and text, with nested spans and entities", () => {
    const html = panel([oldRow("0:00", "good morning"), oldRow("0:04", "let&#39;s start <span>with</span> a <b>system</b> &amp; two lines"), oldRow("1:02:03", "late")]);
    expect(rowsFromHtml(html)).toEqual([
      { timestamp: "0:00", text: "good morning" },
      { timestamp: "0:04", text: "let's start with a system & two lines" },
      { timestamp: "1:02:03", text: "late" },
    ]);
  });

  test("new markup: the accessibility label is not mistaken for the timestamp", () => {
    expect(rowsFromHtml(panel([newRow("0:07", "the row picture"), newRow("0:12", "and the column picture")]))).toEqual([
      { timestamp: "0:07", text: "the row picture" },
      { timestamp: "0:12", text: "and the column picture" },
    ]);
  });

  test("rows missing a timestamp or text are skipped, other rows survive", () => {
    const broken = `<ytd-transcript-segment-renderer><div class="segment-text">orphan</div></ytd-transcript-segment-renderer>`;
    expect(rowsFromHtml(panel([broken, oldRow("0:01", "kept")]))).toEqual([{ timestamp: "0:01", text: "kept" }]);
  });

  test("the footer label gives the language and the auto-generated flag", () => {
    expect(languageFromPanelHtml(panel([], "English (auto-generated)"))).toEqual({ language: "English", autoGenerated: true });
    expect(languageFromPanelHtml(panel([], "Spanish"))).toEqual({ language: "Spanish", autoGenerated: false });
    expect(languageFromPanelHtml("<div>no footer</div>")).toEqual({ language: "unknown", autoGenerated: false });
  });

  test("rows become segments: each ends where the next starts, the last at the video's end", () => {
    const rows = [
      { timestamp: "0:00", text: "a" },
      { timestamp: "0:04", text: "b" },
      { timestamp: "0:10", text: "c" },
    ];
    expect(segmentsFromRows(rows, 20)).toEqual([seg(0, 4, "a"), seg(4, 10, "b"), seg(10, 20, "c")]);
  });

  test("unknown duration, or a duration not past the last start, gives the last row five seconds", () => {
    const rows = [{ timestamp: "0:00", text: "a" }, { timestamp: "0:10", text: "b" }];
    expect(segmentsFromRows(rows, null).at(-1)).toEqual(seg(10, 15, "b"));
    expect(segmentsFromRows(rows, 10).at(-1)).toEqual(seg(10, 15, "b"));
  });

  test("equal timestamps and unparsable rows never produce an empty or inverted segment", () => {
    const rows = [
      { timestamp: "0:05", text: "x" },
      { timestamp: "0:05", text: "y" },
      { timestamp: "bad", text: "z" },
      { timestamp: "0:09", text: "w" },
    ];
    const out = segmentsFromRows(rows, 30);
    expect(out.map((s) => s.text)).toEqual(["x", "y", "w"]);
    for (const s of out) expect(s.end).toBeGreaterThan(s.start);
  });
});

describe("json3 captions", () => {
  const json3 = {
    wireMagic: "pb3",
    events: [
      { tStartMs: 0, dDurationMs: 4000, wWinId: 1 },
      { tStartMs: 480, dDurationMs: 3000, segs: [{ utf8: "so", acAsrConf: 0 }, { utf8: " the", tOffsetMs: 200 }, { utf8: " geometry", tOffsetMs: 400 }] },
      { tStartMs: 3000, dDurationMs: 4000, segs: [{ utf8: "of linear\nequations" }] },
      { tStartMs: 3500, aAppend: 1, segs: [{ utf8: "\n" }] },
      { tStartMs: 7000, segs: [{ utf8: "[Music]" }] },
      { tStartMs: 9000, dDurationMs: 1500, segs: [{ utf8: "  x < y &amp; " }] },
    ],
  };

  test("events with text become millisecond-precision segments; empty and newline-only events are dropped", () => {
    expect(parseJson3(json3).map((s) => [s.start as number, s.end as number, s.text])).toEqual([
      [0.48, 3, "so the geometry"],
      [3, 7, "of linear equations"],
      [7, 9, "[Music]"],
      [9, 10.5, "x < y &amp;"],
    ]);
  });

  test("an event that overlaps the next is cut at the next start so passages never overlap", () => {
    const out = parseJson3({ events: [{ tStartMs: 0, dDurationMs: 5000, segs: [{ utf8: "a" }] }, { tStartMs: 2000, dDurationMs: 1000, segs: [{ utf8: "b" }] }] });
    expect(out).toEqual([seg(0, 2, "a"), seg(2, 3, "b")]);
  });

  test("junk payloads give no segments instead of throwing", () => {
    for (const junk of [null, undefined, 3, "x", {}, { events: "no" }, { events: [null, 1, { tStartMs: "0" }, { tStartMs: 1, segs: "no" }] }]) {
      expect(parseJson3(junk)).toEqual([]);
    }
  });

  test("an event with a negative or non-finite start is skipped, and the rest survive", () => {
    const at = (tStartMs: number, text: string) => ({ tStartMs, dDurationMs: 900, segs: [{ utf8: text }] });
    const out = parseJson3({ events: [at(-3000, "pre-roll"), at(Number.NaN, "nan"), at(Number.POSITIVE_INFINITY, "inf"), at(0, "a"), at(1000, "b")] });
    expect(out.map((s) => s.text)).toEqual(["a", "b"]);
  });
});

describe("usability check", () => {
  const talk = (n: number, each = 6) => Array.from({ length: n }, (_, i) => seg(i * each, (i + 1) * each, `sentence ${i}`));

  test("a full-length transcript of real sentences is usable", () => {
    expect(isUsable(talk(20), 120)).toBe(true);
  });

  test("fewer than five segments is unusable", () => {
    expect(isUsable(talk(4), 24)).toBe(false);
  });

  test("covering less than half the video is unusable; overlapping segments are not double counted", () => {
    expect(isUsable(talk(20), 600)).toBe(false);
    const overlapping = Array.from({ length: 10 }, (_, i) => seg(0, 6 + i * 0.1, `s${i}`));
    expect(isUsable(overlapping, 60)).toBe(false);
  });

  test("a transcript dominated by sound cues is unusable", () => {
    const cues = Array.from({ length: 12 }, (_, i) => seg(i * 10, (i + 1) * 10, i % 4 === 0 ? "plain words" : i % 2 ? "[Music]" : "♪ la la ♪"));
    expect(isUsable(cues, 120)).toBe(false);
  });

  test("an unknown duration skips the coverage check only", () => {
    expect(isUsable(talk(8), null)).toBe(true);
    expect(isUsable(talk(3), null)).toBe(false);
  });

  test("an unusable transcript becomes a transcript_unavailable fact, never a transcript", () => {
    const label = { language: "English", autoGenerated: true };
    expect(buildTranscript("QgWz_s7uugE", "panel", label, talk(2), 60)).toEqual({ kind: "transcript_unavailable", videoId: "QgWz_s7uugE", reason: "unusable" });
    const ok = buildTranscript("QgWz_s7uugE", "caption_intercept", label, talk(12), 72);
    expect(ok).toMatchObject({ kind: "transcript", origin: "caption_intercept", language: "English", autoGenerated: true });
  });

  test("panel HTML to transcript fact, end to end", () => {
    const rows = Array.from({ length: 12 }, (_, i) => oldRow(`${Math.floor((i * 10) / 60)}:${String((i * 10) % 60).padStart(2, "0")}`, `line ${i}`));
    const html = panel(rows);
    const result = buildTranscript("QgWz_s7uugE", "panel", languageFromPanelHtml(html), segmentsFromRows(rowsFromHtml(html), 120), 120);
    expect(result.kind).toBe("transcript");
    if (result.kind === "transcript") {
      expect(result.segments).toHaveLength(12);
      expect(result.segments[11]).toEqual(seg(110, 120, "line 11"));
      expect(result.autoGenerated).toBe(true);
    }
  });
});

describe("caption interception", () => {
  test("only the player's own json3 track requests are tapped", () => {
    expect(parseTimedTextUrl("https://www.youtube.com/api/timedtext?v=QgWz_s7uugE&lang=en&kind=asr&fmt=json3")).toEqual({ videoId: "QgWz_s7uugE", lang: "en", asr: true });
    expect(parseTimedTextUrl("/api/timedtext?v=QgWz_s7uugE&lang=en&fmt=json3")).toEqual({ videoId: "QgWz_s7uugE", lang: "en", asr: false });
    expect(parseTimedTextUrl("https://www.youtube.com/api/timedtext?v=QgWz_s7uugE&lang=en&tlang=fr&fmt=json3")).toBeNull();
    expect(parseTimedTextUrl("https://www.youtube.com/api/timedtext?v=QgWz_s7uugE&fmt=srv3")).toBeNull();
    expect(parseTimedTextUrl("https://www.youtube.com/api/stats/playback?v=QgWz_s7uugE")).toBeNull();
    expect(parseTimedTextUrl("https://www.youtube.com/api/timedtext?lang=en")).toBeNull();
  });

  test("forwarded messages are recognised only with the afterclass envelope", () => {
    const good = { source: "afterclass", kind: "timedtext", videoId: "QgWz_s7uugE", lang: "en", asr: false, payload: {} };
    expect(isTimedTextMessage(good)).toBe(true);
    expect(isTimedTextMessage({ ...good, source: "other" })).toBe(false);
    expect(isTimedTextMessage({ ...good, asr: "no" })).toBe(false);
    expect(isTimedTextMessage(null)).toBe(false);
  });
});

describe("acquireTranscript never hangs", () => {
  const g = globalThis as unknown as Record<string, unknown>;
  const saved = { window: g.window, document: g.document };
  afterEach(() => {
    g.window = saved.window;
    g.document = saved.document;
  });

  function fakeWindow() {
    const listeners: ((e: unknown) => void)[] = [];
    const win = { location: { origin: "https://www.youtube.com" }, addEventListener: (_: string, f: (e: unknown) => void) => listeners.push(f) };
    g.window = win;
    return { deliver: (data: unknown) => listeners.forEach((f) => f({ source: win, origin: win.location.origin, data })) };
  }
  const event = (tStartMs: number, i: number) => ({ tStartMs, dDurationMs: 900, segs: [{ utf8: `sentence number ${i}` }] });

  test("a caption track with a negative start still becomes a transcript instead of vanishing", async () => {
    const { deliver } = fakeWindow();
    startCaptionListener();
    g.document = { querySelector: () => null, querySelectorAll: () => [] };
    const events = [event(-3000, -1), ...Array.from({ length: 8 }, (_, i) => event(i * 1000, i))];
    const pending = acquireTranscript("NEGSTART_aaa", 8, 500);
    deliver({ source: "afterclass", kind: "timedtext", videoId: "NEGSTART_aaa", lang: "en", asr: false, payload: { events } });
    const r = await pending;
    expect(r.kind).toBe("transcript");
    if (r.kind === "transcript") expect(r.segments).toHaveLength(8);
  });

  test("a panel whose rows never stop changing is abandoned at the overall deadline", async () => {
    fakeWindow();
    let rows = 0;
    const panel = { getAttribute: () => "ENGAGEMENT_PANEL_VISIBILITY_EXPANDED", querySelectorAll: () => Array.from({ length: ++rows }), outerHTML: "", querySelector: () => null };
    g.document = { querySelector: () => panel, querySelectorAll: () => [] };
    const started = Date.now();
    const r = await acquireTranscript("NEVERSETTLE", 600, 100, 400);
    expect(r.kind).toBe("transcript_unavailable");
    expect(Date.now() - started).toBeLessThan(2000);
  });
});
