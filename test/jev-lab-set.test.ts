/** A JPEG header the Jev adapter accepts (640x360). The last byte tells the scripted client which frame it is. */
const jpeg = (tag: number, pad = 0) => Buffer.from([0xff, 0xd8, 0xff, 0xc0, 0x00, 0x11, 0x08, 0x01, 0x68, 0x02, 0x80, ...new Array<number>(8 + pad).fill(0), tag]);

type Frm = { id: string; at: number; tag: number; pad?: number };
/** One clip watched from 0 to `len` in order. Captions are 10 s; one starts a new topic where `topics` says (the first caption of a clip is a new topic unless `opening` is false). */
type ClipSpec = { videoId: string; len: number; topics?: number[]; opening?: boolean; frames?: Frm[] };

const segmentsOf = (c: ClipSpec) => {
  const out: { start: number; end: number; text: string }[] = [];
  for (let t = 0; t < c.len; t += 10) {
    const topic = (c.topics ?? []).includes(t) || (t === 0 && c.opening !== false);
    out.push({ start: t, end: Math.min(c.len, t + 10), text: topic ? `NEWTOPIC ${c.videoId} ${t}` : `caption ${c.videoId} ${t}` });
  }
  return out;
};

function makeCapture(clips: readonly ClipSpec[]): { dir: string; captureId: CaptureId } {
  const dir = tmp("capture");
  const db = openDb(join(dir, "afterclass.sqlite"));
  const keyOf = (input: { readonly after: { readonly frame: { readonly id: string } } }): MemoKey => stableId("key", "frame_change", "test", input.after.frame.id);
  const evidence = createEvidence(db, dir, { lookupFrameChange: (i) => ({ kind: "missing", key: keyOf(i) }), runFrameChange: async () => undefined, frameChangeKey: keyOf, onChange: () => {} });
  const captureId = randomId("cap");
  const bodies: CaptureFactBody[] = [{ kind: "control", action: "start", reason: "user" }];
  for (const c of clips) {
    bodies.push(
      { kind: "source", videoId: c.videoId, title: `Clip ${c.videoId[0]}`, channelName: "Prof", url: `https://www.youtube.com/watch?v=${c.videoId}`, durationS: c.len },
      { kind: "transcript", videoId: c.videoId, origin: "panel", language: "en", autoGenerated: false, segments: segmentsOf(c).map((s) => ({ start: media(s.start), end: media(s.end), text: s.text })) },
      { kind: "span", videoId: c.videoId, start: media(0), end: media(c.len), rate: 1, tabVisible: true, wallDurationMs: c.len * 1000 },
      ...(c.frames ?? []).map((f): CaptureFactBody => ({ kind: "frame", videoId: c.videoId, frameId: f.id, mediaS: media(f.at), width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: jpeg(f.tag, f.pad).toString("base64") })),
    );
  }
  bodies.push({ kind: "control", action: "stop", reason: "user" });
  evidence.ingest({ captureId, facts: bodies.map((b, i) => ({ captureId, clientSeq: i, wallMs: 1000 + i, ...b }) as CaptureFact) });
  db.close();
  return { dir, captureId };
}

/** p that the change adds teaching content, by the frame's tag. */
const FRAME_P: Record<number, number> = { 1: 0.05, 2: 0.05, 3: 0.9, 4: 0.5, 5: 0.9, 6: 0.9 };

type Scripted = JevClient & { readonly requests: JevRequest<string>[] };
function scripted(): Scripted {
  const requests: JevRequest<string>[] = [];
  return {
    requests,
    async ask<Q extends string>(req: JevRequest<Q>) {
      requests.push(req);
      const answers: Record<string, JevAnswer> = {};
      if ("new_concept" in req.questions) {
        const text = (req.state as { passage: { text: string }[] }).passage.map((p) => p.text).join(" ");
        const p = text.includes("NEWTOPIC") ? 0.95 : 0.1;
        answers.new_concept = { type: "noul", p };
        answers.stopping_point = { type: "noul", p };
      } else answers.teaching_change = { type: "noul", p: FRAME_P[req.images[1]!.bytes.at(-1)!] ?? 0.9 };
      return { answers: answers as Record<Q, JevAnswer>, usage: { model: req.model, inputTokens: 100, outputTokens: 5, cacheReadTokens: null, cost: { kind: "unknown", reason: "fake" } } };
    },
  };
}

const signed = { status: "signed_off", signedOffBy: "Derek (test fixture)", signedOffAt: "2026-11-05" } as const;
const item = (mediaS: number, extra: Record<string, unknown> = {}) => ({ mediaS, note: "", confirmed: true, ...extra });

function writeLabels(dir: string, labels: Record<string, unknown>, name: string): string {
  const path = join(dir, name);
  writeFileSync(path, JSON.stringify(labels, null, 2));
  return path;
}

function labRun(clips: readonly ClipSpec[], labelFiles: (captureId: string, dir: string) => string[]) {
  const { dir: dataDir, captureId } = makeCapture(clips);
  const labDir = tmp("lab");
  const files = labelFiles(captureId, tmp("labels"));
  let t = 0;
  const base = (client: JevClient = scripted()): Omit<RunOptions, "phase"> => ({ dataDir, labDir, labelFiles: files, live: false, client, now: () => (t += 5), retryDelayMs: () => 0, out: () => {} });
  return { dataDir, labDir, captureId, files, base };
}

/** The random capture id and the label hash are not part of what a report says about the lab's numbers. */
const normalize = (text: string) => text.replace(/cap_[a-z0-9]+/g, "CAP").replace(/sha256 [0-9a-f]{12}/g, "sha256 X");

