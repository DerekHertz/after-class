export const JPEG = Buffer.from(JPEG_BYTES);

export const scratch: string[] = [];
export const running: Running[] = [];
/** Stops every backend a test booted and removes its directories. Each test file runs it after each test. */
export async function cleanup(): Promise<void> {
  for (const r of running.splice(0)) await r.stop();
  for (const d of scratch.splice(0)) rmSync(d, { recursive: true, force: true });
}

export function dir(prefix: string): string {
  const d = mkdtempSync(join(tmpdir(), prefix));
  scratch.push(d);
  return d;
}

export type Boot = { readonly r: Running; readonly logs: string[]; readonly errors: string[]; readonly configDir: string; readonly dataDir: string; readonly base: string };

export async function boot(options: MainOptions = {}, env: Record<string, string | undefined> = {}): Promise<Boot> {
  const configDir = options.configDir ?? dir("afterclass-config-");
  const dataDir = dir("afterclass-data-");
  const logs: string[] = [];
  const errors: string[] = [];
  const r = await main({
    port: 0, buildApp: false, configDir, log: (t) => void logs.push(t), error: (t) => void errors.push(t),
    ...options, env: { AFTERCLASS_DATA: dataDir, ...env },
  });
  running.push(r);
  return { r, logs, errors, configDir, dataDir, base: `http://127.0.0.1:${r.port}` };
}

export const until = async (done: () => boolean, ms = 10_000): Promise<void> => {
  const end = Date.now() + ms;
  while (!done()) {
    if (Date.now() > end) throw new Error("timed out waiting");
    await Bun.sleep(20);
  }
};

