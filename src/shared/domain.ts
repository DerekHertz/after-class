/**
 * Core domain types: parsed, trusted shapes only. Wire shapes live in wire.ts,
 * and no domain module imports wire.ts.
 *
 * Three kinds of state, and every type below is one of them:
 *
 *   FACT        immutable, append-only, owned by exactly one actor
 *               (extension, user, provider memo). Never updated.
 *   DERIVATION  a pure function of facts. Never stored as truth; recomputed.
 *   SNAPSHOT    a derivation frozen at a user-visible moment and stored under a
 *               content-derived ID (chunk revisions, review scope, saved record).
 *
 * Frozen by the kernel (W10). A change goes through W10, never a worker.
 */
import type {
  CaptureId, ChunkId, ChunkRevisionId, ClaimId, ConceptId, EvidenceId, LinkId, MemoKey,
  NoteId, ObservationId, ResourceId, ReviewId, SourceId, ThreadId, TranscriptRevId, TurnId,
  UsageEventId, WindowId,
} from "./ids";
import type { Interval, Material, MediaSeconds } from "./time";

declare const SeqBrand: unique symbol;
/** Global monotonic order of every fact the backend accepts. Only db.nextSeq mints one. */
export type Seq = number & { readonly [SeqBrand]: true };

export type NonEmpty<T> = readonly [T, ...T[]];

// ───────────────────────────── Capture facts (owner: extension) ─────────────

export type CaptureControl = "start" | "pause" | "resume" | "stop";
export type ControlReason = "user" | "left_watch_page" | "returned_to_watch_page" | "tab_closed";
export type TranscriptOrigin = "panel" | "caption_intercept" | "asr";
export type Channel = "transcript" | "frames" | "playback";

/**
 * One observation from the extension. (captureId, clientSeq) is the
 * idempotency key, so resending a batch is a no-op.
 * `wallMs` is for ordering and diagnostics only, never for evidence.
 */
export type CaptureFact = {
  readonly captureId: CaptureId;
  readonly clientSeq: number;
  readonly wallMs: number;
} & CaptureFactBody;

/** How the tracker knew an ad was playing. Either signal alone suspends evidence (fail closed). */
export type AdSignal = "dom_class" | "duration_mismatch";

export type CaptureFactBody =
  | { readonly kind: "control"; readonly action: CaptureControl; readonly reason: ControlReason }
  | { readonly kind: "source"; readonly videoId: string; readonly title: string; readonly channelName: string; readonly url: string; readonly durationS: number | null }
  /** The whole transcript as published. Source text, not evidence: only clipping to watched intervals makes evidence. */
  | { readonly kind: "transcript"; readonly videoId: string; readonly origin: TranscriptOrigin; readonly language: string; readonly autoGenerated: boolean; readonly segments: readonly TranscriptSegment[] }
  | { readonly kind: "transcript_unavailable"; readonly videoId: string; readonly reason: "no_captions" | "panel_missing" | "unusable" | "intercept_failed" }
  /**
   * Content playback only. The tracker closes a span before any ad starts.
   * `wallDurationMs` lets the backend quarantine spans that grew faster than
   * wall time or past the source duration (span plausibility, R2 defence in depth).
   */
  | { readonly kind: "span"; readonly videoId: string; readonly start: MediaSeconds; readonly end: MediaSeconds; readonly rate: number; readonly tabVisible: boolean; readonly wallDurationMs: number }
  /** Ad time is its own fact kind; nothing that derives evidence reads it. */
  | { readonly kind: "ad"; readonly videoId: string; readonly atContentS: MediaSeconds; readonly wallDurationMs: number; readonly signals: NonEmpty<AdSignal> }
  /** JPEG capped at 1280 px on the long side at capture, so it meets Jev's 280–1568 px bounds without a backend decoder. */
  | { readonly kind: "frame"; readonly videoId: string; readonly frameId: string; readonly mediaS: MediaSeconds; readonly width: number; readonly height: number; readonly trigger: FrameTrigger; readonly diff: number; readonly jpegBase64: string }
  | { readonly kind: "channel"; readonly channel: Channel; readonly health: "ok" | "failed" | "stalled"; readonly videoId: string | null; readonly atMediaS: MediaSeconds | null; readonly detail: string }
  | { readonly kind: "transcription_choice"; readonly videoId: string; readonly choice: "accept_asr" | "continue_with_gap" };

export type CaptureFactKind = CaptureFactBody["kind"];

