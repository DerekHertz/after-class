describe("experiment 6 total of 5,000 Jev calls", () => {
  const seed = (labDir: string, arm: string, callsUsed: number) => {
    const d = armState(labDir, arm, "live");
    mkdirSync(d, { recursive: true });
    writeFileSync(join(d, "state.json"), JSON.stringify({ version: 1, callsUsed, tuneRounds: 0, lastTune: null, scoreStatus: "none" }));
  };
  const live = (o: ReturnType<typeof lab>, over: Partial<RunOptions> = {}): RunOptions => ({
    ...o.base(), live: true, maxCalls: 50, keysPath: keysFile(), fetch: stubFetch().fn, phase: "tune", arm: "a", armConfig: productConfig(), ...over,
  });

  test("the constant is 5000", () => {
    expect(EXP6_BUDGET_CALLS).toBe(5000);
  });

  test("a run that would cross 5000 across the arm directories refuses up front, before any request", async () => {
    const o = lab();
    seed(o.labDir, "other", 4996);
    const f = stubFetch();
    await expect(runLab(live(o, { fetch: f.fn }))).rejects.toThrow("needs 7 new calls and 4996 of 5000 are used across the experiment 6 arm directories; no call was made");
    expect(f.seen).toHaveLength(0);
  });

  test("a run that fits exactly is allowed, and the request that would cross is never sent, even through retries", async () => {
    const o = lab();
    seed(o.labDir, "other", 4993);
    const ok = stubFetch();
    await runLab(live(o, { fetch: ok.fn, arm: "fits" }));
    expect(ok.seen).toHaveLength(7);

    const o2 = lab();
    seed(o2.labDir, "other", 4993);
    const f = stubFetch({ fail: "503" });
    await expect(runLab(live(o2, { fetch: f.fn, maxCalls: 100 }))).rejects.toThrow("experiment 6 budget of 5000");
    expect(f.seen).toHaveLength(7);
    expect(readState(armState(o2.labDir, "a", "live")).callsUsed).toBe(7);
  });

  test("deleting an arm's state.json does not reset the total: its stored judgments floor its count", async () => {
    const o = lab();
    await runLab(live(o, { arm: "b" }));
    rmSync(join(armState(o.labDir, "b", "live"), "state.json"));
    seed(o.labDir, "c", 4994);
    const f = stubFetch();
    await expect(runLab(live(o, { fetch: f.fn, arm: "a" }))).rejects.toThrow("5001 of 5000 are used across the experiment 6 arm directories");
    expect(f.seen).toHaveLength(0);
  });

  test("fixture and live directories count separately, and the arm's own directory is not double counted", async () => {
    const o = lab();
    seed(o.labDir, "other", 4999);
    const f = stubFetch();
    await runLab({ ...o.base(), phase: "tune", arm: "a", armConfig: productConfig() });
    expect(f.seen).toHaveLength(0);
    const own = lab();
    seed(own.labDir, "a", 4990);
    await expect(runLab(live(own, { fetch: stubFetch().fn }))).rejects.toThrow("are used; no call was made");
  });
});

// ───────────────────────────── selected-round scoring ─────────────────────────────

function fakeReport(verdicts: readonly ("PASS" | "FAIL" | "NOT MEASURED")[], recall: [number, number], falseCloses: number | null): Report {
  return {
    text: "", overall: "FAIL", exitCode: 1,
    bars: verdicts.map((verdict, i) => ({ name: ["recall", "false closes", "visual steps", "duplicates"][i]!, verdict })),
    metrics: { recallMatched: recall[0], recallLabeled: recall[1], falseCloses },
  };
}
const P = "PASS";
const F = "FAIL";
const rr = (round: number, report: Report): RoundReport => ({ round, report });

describe("selectRound (decision 5)", () => {
  test("the most clauses passed wins, even over a later or higher-recall round", () => {
    const sel = selectRound([rr(1, fakeReport([P, P, F, F], [1, 5], 3)), rr(2, fakeReport([P, P, P, F], [1, 5], 9)), rr(3, fakeReport([P, F, F, F], [5, 5], 0))]);
    expect(sel.round).toBe(2);
    expect(sel.reason).toContain("most clauses passed");
    expect(sel.reason).toContain("round 1: 2 of 4 clauses pass");
    expect(sel.reason).toContain("round 2: 3 of 4 clauses pass");
  });

  test("a tie on clauses goes to the higher boundary recall (a ratio, not a count)", () => {
    const sel = selectRound([rr(1, fakeReport([P, F, F, F], [2, 5], 0)), rr(2, fakeReport([P, F, F, F], [3, 5], 4)), rr(3, fakeReport([P, F, F, F], [4, 10], 0))]);
    expect(sel.round).toBe(2);
    expect(sel.reason).toContain("higher boundary recall");
    expect(sel.reason).toContain("recall 3/5");
  });

  test("a tie on clauses and recall goes to fewer false closes", () => {
    const sel = selectRound([rr(1, fakeReport([P, F, F, F], [2, 5], 4)), rr(2, fakeReport([P, F, F, F], [2, 5], 1)), rr(3, fakeReport([P, F, F, F], [2, 5], 2))]);
    expect(sel.round).toBe(2);
    expect(sel.reason).toContain("fewer false closes");
  });

  test("a full tie goes to the earlier round, whatever order the reports arrive in", () => {
    const same = () => fakeReport([P, F, F, F], [2, 5], 1);
    const sel = selectRound([rr(3, same()), rr(1, same()), rr(2, same())]);
    expect(sel.round).toBe(1);
    expect(sel.reason).toContain("earlier round");
  });

  test("a clause or recall that was not measured never beats a measured one; one round selects itself", () => {
    expect(selectRound([rr(1, fakeReport([P, F, F, F], [0, 0], null)), rr(2, fakeReport([P, F, F, F], [0, 4], 6))]).round).toBe(2);
    expect(selectRound([rr(1, fakeReport([P, P, P, P], [1, 1], 0))])).toMatchObject({ round: 1 });
    expect(() => selectRound([])).toThrow("at least one");
  });
});

describe("scoring an arm's selected round", () => {
  /** Round 1: good wording (3 clauses pass on the first half). Round 2: BAD wording and other thresholds (recall fails). Round 2 is the LAST round. */
  async function twoRounds(o: ReturnType<typeof lab>, arm: string) {
    const good = withWording(productConfig(), "Good");
    const bad: ArmConfig = { ...withWording(productConfig(), "BAD"), thresholds: { yesAtOrAbove: 0.6, noAtOrBelow: 0.2 }, segmentation: { ...SEGMENTATION_DEFAULTS, contextS: 60 } };
    const r1 = await runLab({ ...o.base(), phase: "tune", arm, armConfig: good });
    const r2 = await runLab({ ...o.base(), phase: "tune", arm, armConfig: bad });
    return { good, bad, r1, r2 };
  }

  test("the scored run uses the selected round's config, thresholds and wording, and records the round and why", async () => {
    const o = lab();
    const { good, r1, r2 } = await twoRounds(o, "sel");
    expect(r1.report.bars.filter((b) => b.verdict === "PASS").length).toBeGreaterThan(r2.report.bars.filter((b) => b.verdict === "PASS").length);

    const client = scripted();
    const run = await runLab({ ...o.base(client), phase: "score", arm: "sel" });
    const h = parseResults(readFileSync(run.resultsPath, "utf8")).header;
    expect(h.selectedRound).toBe(1);
    expect(h.selectionReason).toContain("most clauses passed");
    expect(h.selectionReason).toContain("round 2: ");
    expect(h.config).toEqual(good.segmentation);
    expect(h.thresholds).toEqual(good.thresholds);
    expect(h.questions).toEqual(good.questions);
    const sentNew = client.requests.filter((r) => "new_concept" in r.questions);
    expect(sentNew.length).toBeGreaterThan(0);
    expect(sentNew.every((r) => (r.questions.new_concept as { instructions: string }).instructions === "Good new concept?")).toBe(true);
    expect(run.report.text).toContain("[fixture] Selected round: 1 of this arm's tune rounds (most clauses passed;");
    expect(run.report.text).toContain("Scope: held-out second halves (scored once)");
    expect(existsSync(join(armState(o.labDir, "sel"), "runs", "score-1.jsonl"))).toBe(true);
    // the selection is read from stored first-half results only: a rescore reproduces the stored text
    expect(reportFromFile(run.resultsPath, o.base().labelFiles).text).toBe(run.report.text);
  });

  test("an arm scores once per directory: a second score refuses and points at rescore; another arm can still score", async () => {
    const o = lab();
    await twoRounds(o, "one");
    await runLab({ ...o.base(), phase: "tune", arm: "two", armConfig: productConfig() });
    await runLab({ ...o.base(), phase: "score", arm: "one" });
    const client = scripted();
    await expect(runLab({ ...o.base(client), phase: "score", arm: "one" })).rejects.toThrow("already scored once");
    await expect(runLab({ ...o.base(client), phase: "score", arm: "one" })).rejects.toThrow("rescore");
    expect(client.requests).toHaveLength(0);
    await runLab({ ...o.base(), phase: "score", arm: "two" });
    expect(readState(armState(o.labDir, "two")).scoreStatus).toBe("complete");
  });

  test("an arm score takes no tuning flags and no arm config, and needs a tune round first", async () => {
    const o = lab();
    await expect(runLab({ ...o.base(), phase: "score", arm: "a" })).rejects.toThrow("no tune round has run yet");
    await runLab({ ...o.base(), phase: "tune", arm: "a", armConfig: productConfig() });
    await expect(runLab({ ...o.base(), phase: "score", arm: "a", overrides: { windowNewS: 20 } })).rejects.toThrow("takes no tuning flags");
    await expect(runLab({ ...o.base(), phase: "score", arm: "a", armConfig: productConfig() })).rejects.toThrow("takes no --arm-config");
  });

  test("experiment 2 (no --arm) still scores the last tune round", async () => {
    const o = lab();
    await runLab({ ...o.base(), phase: "tune" });
    await runLab({ ...o.base(), phase: "tune", overrides: { yesAtOrAbove: 0.9 } });
    const run = await runLab({ ...o.base(), phase: "score" });
    const h = parseResults(readFileSync(run.resultsPath, "utf8")).header;
    expect(h.thresholds.yesAtOrAbove).toBe(0.9);
    expect(h.selectedRound).toBeUndefined();
    expect(run.report.text).not.toContain("Selected round");
  });
});

