describe("validateArmConfig", () => {
  const good = () => JSON.parse(JSON.stringify(productConfig())) as Record<string, any>;
  const errorsOf = (x: unknown) => {
    const r = validateArmConfig(x);
    return r.ok ? [] : r.errors;
  };

  test("the baseline config is valid and carries the product wording, thresholds and segmentation", () => {
    const r = validateArmConfig(good());
    expect(r.ok).toBe(true);
    expect(r.ok && r.config).toEqual({ schemaVersion: 1, kind: "jev-arm-config", questions: PRODUCT_QUESTIONS, thresholds: DEFAULT_THRESHOLDS, segmentation: SEGMENTATION_DEFAULTS });
    const lt = { config: { ...SEGMENTATION_DEFAULTS, windowNewS: 45 }, thresholds: { yesAtOrAbove: 0.4, noAtOrBelow: 0.2 } };
    expect(armConfigFromBaseline(lt)).toMatchObject({ thresholds: lt.thresholds, segmentation: lt.config, questions: PRODUCT_QUESTIONS });
  });

  test("an unknown key anywhere is an error (model, routing, labels, split, scoring, sampler)", () => {
    for (const key of ["model", "routing", "labels", "split", "scoring", "frameSampler"]) expect(errorsOf({ ...good(), [key]: 1 }).join("\n")).toContain(`${key} is not allowed`);
    const a = good();
    a.questions.type = "noul";
    expect(errorsOf(a).join("\n")).toContain("questions.type is not allowed");
    const b = good();
    b.segmentation.model = "x";
    expect(errorsOf(b).join("\n")).toContain("segmentation.model is not allowed");
    const c = good();
    c.thresholds.extra = 1;
    expect(errorsOf(c).join("\n")).toContain("thresholds.extra is not allowed");
  });

  test("missing keys, wrong schema or kind, and non-objects are errors", () => {
    expect(errorsOf(null)).toHaveLength(1);
    const a = good();
    delete a.questions.teachingChange;
    delete a.segmentation;
    a.schemaVersion = 2;
    a.kind = "other";
    const text = errorsOf(a).join("\n");
    expect(text).toContain("questions.teachingChange is missing");
    expect(text).toContain("segmentation must be an object");
    expect(text).toContain("schemaVersion must be 1");
    expect(text).toContain("kind must be");
  });

  test("each wording is a non-empty string of at most 600 characters", () => {
    for (const bad of ["", "   ", 5, null]) {
      const a = good();
      a.questions.newConcept = bad;
      expect(errorsOf(a).join("\n")).toContain("questions.newConcept must be a non-empty string");
    }
    const ok = good();
    ok.questions.stoppingPoint = "x".repeat(600);
    expect(errorsOf(ok)).toEqual([]);
    ok.questions.stoppingPoint = "x".repeat(601);
    expect(errorsOf(ok).join("\n")).toContain("601 characters; at most 600");
  });

  test("the numeric ranges are exactly resolveTuning's", () => {
    const bad = (path: "thresholds" | "segmentation", key: string, v: unknown) => {
      const a = good();
      a[path][key] = v;
      return errorsOf(a).join("\n");
    };
    expect(bad("segmentation", "windowNewS", 0)).toContain("segmentation out of range");
    expect(bad("segmentation", "contextS", -1)).toContain("segmentation out of range");
    expect(bad("segmentation", "timeCapS", 30)).toContain("segmentation out of range");
    expect(bad("segmentation", "maxFramesPerWindow", 5)).toContain("segmentation out of range");
    expect(bad("segmentation", "maxFramesPerWindow", 1.5)).toContain("segmentation out of range");
    expect(bad("segmentation", "maxFramesPerWindow", "2")).toContain("must be a number");
    expect(bad("segmentation", "reviseOnNextNoNo", "yes")).toContain("true or false");
    expect(bad("thresholds", "yesAtOrAbove", 1.1)).toContain("thresholds out of range");
    expect(bad("thresholds", "noAtOrBelow", 0.7)).toContain("thresholds out of range");
    expect(bad("thresholds", "noAtOrBelow", -0.1)).toContain("thresholds out of range");
    const edge = good();
    edge.segmentation.maxFramesPerWindow = 0;
    edge.segmentation.contextS = 0;
    edge.thresholds = { yesAtOrAbove: 1, noAtOrBelow: 0 };
    expect(errorsOf(edge)).toEqual([]);
  });
});

