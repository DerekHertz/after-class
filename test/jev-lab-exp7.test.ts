function fakeClient(respond: (n: number) => string): { client: ClaudeCli; requests: ClaudeRequest[] } {
  const requests: ClaudeRequest[] = [];
  const client: ClaudeCli = {
    async structured() {
      throw new Error("the optimizer must not use structured()");
    },
    async streamText(req) {
      requests.push(req);
      return { text: respond(requests.length), usage: { model: "claude-fable-5-1", inputTokens: 10, outputTokens: 5, cacheReadTokens: null, cost: { kind: "unknown", reason: "fake" } } } as never;
    },
  } as ClaudeCli;
  return { client, requests };
}

let counter = 0;
function options(h: Harness, over: Partial<OptimizeOptions> = {}): { opts: OptimizeOptions; requests: ClaudeRequest[]; outDir: string } {
  const { client, requests } = fakeClient(() => proposal7());
  const outDir = join(h.ledger, `opt-${++counter}`);
  const opts: OptimizeOptions = {
    dataDir: h.dataDir, labelFile: h.labelFile, labDir: h.labDir, arm: "x7", model: "claude-fable-5-1", outDir, live: false, client, exp7: true,
    fromResults: [h.baseTune], previousDirs: [], heldOutReportPath: h.baseScoreReport, now: () => 1000, out: () => {}, ...over,
  };
  return { opts, requests, outDir: String(opts.outDir) };
}
const inputsOf = (o: OptimizeOptions): OptimizeInputs => ({
  dataDir: o.dataDir, labelFile: o.labelFile, labDir: o.labDir, arm: o.arm, fromResults: o.fromResults, previousDirs: o.previousDirs, exp7: true,
  ...(o.heldOutReportPath ? { heldOutReportPath: o.heldOutReportPath } : {}),
});
const prepared = (h: Harness) => {
  const { opts } = options(h);
  const inp = inputsOf(opts);
  const ctx = resolveRound(inp, loadLabels([inp.labelFile])[0]!);
  return { inp, ctx, built: buildOptimizerPrompt(inp, ctx) };
};

