describe("response validation", () => {
  const f = sharedFixture();
  const a = idsOf(f, A);
  const b = idsOf(f, B);
  const callA = callOf(f.dataDir, f.captureId, A);
  const callB2 = callOf(f.dataDir, f.captureId, B, 1);
  const ok = { boundaries: [{ mediaS: 40.5, reason: "New topic." }], visualSteps: [{ mediaS: 30, reason: "New slide." }], duplicateGroups: [{ frames: [{ frameId: a[0]!, mediaS: 10 }, { frameId: a[1]!, mediaS: 30 }], reason: "Same." }] };
  const bad = (over: Record<string, unknown>) => parseResponse(JSON.stringify({ ...ok, ...over }), callA);
  const error = (r: ReturnType<typeof parseResponse>) => (r.ok ? "" : r.error);

  test("a valid answer is accepted exactly as given", () => {
    const r = parseResponse(JSON.stringify(ok), callA);
    expect(r).toEqual({ ok: true, value: ok });
  });

  test("one fenced block is read, prose around it is not", () => {
    expect(parseResponse("```json\n" + JSON.stringify(ok) + "\n```", callA).ok).toBe(true);
    expect(error(parseResponse("Here you go: " + JSON.stringify(ok), callA))).toMatch(/JSON/);
  });

  test("refuses what is not one object with exactly the three arrays", () => {
    expect(error(parseResponse("not json", callA))).toMatch(/JSON/);
    expect(error(parseResponse("[]", callA))).toMatch(/object/);
    expect(error(parseResponse(JSON.stringify({ boundaries: [], visualSteps: [] }), callA))).toContain("duplicateGroups");
    expect(error(bad({ notes: "x" }))).toContain("notes");
    expect(error(bad({ boundaries: [{ mediaS: 5, reason: "x", extra: 1 }] }))).toContain("extra");
  });

  test("refuses times that are not numbers or lie outside the clip's watched span (half-open)", () => {
    expect(error(bad({ boundaries: [{ mediaS: "12", reason: "x" }] }))).toContain("boundaries[0].mediaS");
    expect(error(bad({ boundaries: [{ mediaS: -1, reason: "x" }] }))).toContain("boundaries[0].mediaS");
    expect(error(bad({ boundaries: [{ mediaS: 100, reason: "x" }] }))).toContain("boundaries[0].mediaS");
    expect(error(bad({ visualSteps: [{ mediaS: 250, reason: "x" }] }))).toContain("visualSteps[0].mediaS");
    expect(bad({ boundaries: [{ mediaS: 0, reason: "x" }] }).ok).toBe(true);
    expect(bad({ boundaries: [{ mediaS: 99.9, reason: "x" }] }).ok).toBe(true);
  });

  test("refuses an empty reason", () => {
    expect(error(bad({ visualSteps: [{ mediaS: 30, reason: "  " }] }))).toContain("visualSteps[0].reason");
  });

  test("refuses duplicate frames that do not exist, are not in this call, disagree with their time, or sit in two groups", () => {
    const group = (frames: unknown[]) => bad({ duplicateGroups: [{ frames, reason: "x" }] });
    expect(error(group([{ frameId: "zzz", mediaS: 10 }, { frameId: a[1]!, mediaS: 30 }]))).toContain("zzz");
    expect(error(group([{ frameId: a[0]!, mediaS: 11 }, { frameId: a[1]!, mediaS: 30 }]))).toContain(a[0]!);
    expect(error(group([{ frameId: a[0]!, mediaS: 10 }]))).toMatch(/at least 2/);
    expect(error(group([{ frameId: a[0]!, mediaS: 10 }, { frameId: a[0]!, mediaS: 10 }]))).toMatch(/twice|distinct/);
    expect(error(bad({ duplicateGroups: [{ frames: [{ frameId: a[0]!, mediaS: 10 }, { frameId: a[1]!, mediaS: 30 }], reason: "x" }, { frames: [{ frameId: a[1]!, mediaS: 30 }, { frameId: a[2]!, mediaS: 50 }], reason: "y" }] }))).toContain(a[1]!);
    // b30 exists in the clip but is shown only by the first call of B's chunks? No: it is in the second. The first call may not cite it.
    const first = callOf(f.dataDir, f.captureId, B, 0);
    expect(error(parseResponse(JSON.stringify({ boundaries: [], visualSteps: [], duplicateGroups: [{ frames: [{ frameId: b[0]!, mediaS: 1 }, { frameId: b[29]!, mediaS: 59 }], reason: "x" }] }), first))).toContain(b[29]!);
    expect(parseResponse(JSON.stringify({ boundaries: [], visualSteps: [], duplicateGroups: [{ frames: [{ frameId: b[21]!, mediaS: 43 }, { frameId: b[29]!, mediaS: 59 }], reason: "x" }] }), callB2).ok).toBe(true);
  });

  test("a frame given by its time alone must be a shown frame's time and is kept as the frame it names; nothing is invented", () => {
    const r = parseResponse(JSON.stringify({ boundaries: [], visualSteps: [], duplicateGroups: [{ frames: [{ mediaS: 10 }, { mediaS: 30 }], reason: "x" }] }), callA);
    expect(r).toEqual({ ok: true, value: { boundaries: [], visualSteps: [], duplicateGroups: [{ frames: [{ frameId: a[0]!, mediaS: 10 }, { frameId: a[1]!, mediaS: 30 }], reason: "x" }] } });
    expect(error(parseResponse(JSON.stringify({ boundaries: [], visualSteps: [], duplicateGroups: [{ frames: [{ mediaS: 10 }, { mediaS: 31 }], reason: "x" }] }), callA))).toContain("31");
  });
});

// ───────────────────────────── the merge of chunks ─────────────────────────────

describe("deterministic merge of chunk proposals", () => {
  const chunk1 = { boundaries: [{ mediaS: 20, reason: "one" }, { mediaS: 25, reason: "two, same call" }], visualSteps: [{ mediaS: 40, reason: "step c1" }], duplicateGroups: [{ frames: [{ frameId: "b22", mediaS: 43 }, { frameId: "b23", mediaS: 45 }], reason: "dup c1" }] };
  const chunk2 = { boundaries: [{ mediaS: 24, reason: "same as one, seen again" }, { mediaS: 50, reason: "later" }], visualSteps: [{ mediaS: 52, reason: "step c2" }, { mediaS: 40.5, reason: "same as c1's step" }], duplicateGroups: [{ frames: [{ frameId: "b23", mediaS: 45 }, { frameId: "b24", mediaS: 47 }], reason: "dup c2" }, { frames: [{ frameId: "b27", mediaS: 53 }, { frameId: "b28", mediaS: 55 }], reason: "dup other" }] };

  test("an item within the merge tolerance of an earlier call's item is the same item and the earlier call's wording is kept; items of one call are never merged with each other", () => {
    expect(MERGE_TOLERANCE_S).toBe(10);
    const m = mergeChunks([chunk1, chunk2]);
    expect(m.boundaries).toEqual([{ mediaS: 20, reason: "one" }, { mediaS: 25, reason: "two, same call" }, { mediaS: 50, reason: "later" }]);
    expect(m.visualSteps).toEqual([{ mediaS: 40, reason: "step c1" }, { mediaS: 52, reason: "step c2" }]);
  });

  test("duplicate groups from different calls that share a frame become one group (frames by time, the first call's reason); others stay", () => {
    const m = mergeChunks([chunk1, chunk2]);
    expect(m.duplicateGroups).toEqual([
      { frames: [{ frameId: "b22", mediaS: 43 }, { frameId: "b23", mediaS: 45 }, { frameId: "b24", mediaS: 47 }], reason: "dup c1" },
      { frames: [{ frameId: "b27", mediaS: 53 }, { frameId: "b28", mediaS: 55 }], reason: "dup other" },
    ]);
  });

  test("the same input gives the same output, and one chunk merges to itself sorted", () => {
    expect(mergeChunks([chunk1, chunk2])).toEqual(mergeChunks([chunk1, chunk2]));
    expect(mergeChunks([{ boundaries: [{ mediaS: 9, reason: "b" }, { mediaS: 3, reason: "a" }], visualSteps: [], duplicateGroups: [] }]).boundaries.map((b) => b.mediaS)).toEqual([3, 9]);
  });
});

