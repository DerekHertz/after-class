    questions: { newConcept: "Does the new passage start a materially different subject from the explanation before it?", stoppingPoint: "Has the earlier explanation reached a natural place to pause?", teachingChange: "Does the second image add new teaching content compared with the first?" },
    thresholds: { yesAtOrAbove: 0.6, noAtOrBelow: 0.3 },
