describe("plan with an arm config", () => {
  test("without one, plan is exactly as before; with different segmentation it counts that config's windows", () => {
    const o = lab();
    const plain = planLab({ dataDir: o.dataDir, labelFiles: [o.labels] });
    expect(plain.tuneRoundCalls).toBe(7);
    expect(plain.lines.join("\n")).not.toContain("Arm config");
    const wide: ArmConfig = { ...productConfig(), segmentation: { ...SEGMENTATION_DEFAULTS, windowNewS: 60 } };
    const planned = planLab({ dataDir: o.dataDir, labelFiles: [o.labels], armConfig: wide });
    expect(planned.tuneRoundCalls).toBeLessThan(plain.tuneRoundCalls);
    expect(planned.lines.join("\n")).toContain("Arm config: windowNewS=60");
  });

  test("with a cache dir, an arm's stored judgments are not new; changed wording makes every judgment new", async () => {
    const o = lab();
    await runLab({ ...o.base(), phase: "tune", arm: "a", armConfig: productConfig() });
    const cacheDir = armState(o.labDir, "a");
    expect(planLab({ dataDir: o.dataDir, labelFiles: [o.labels], armConfig: productConfig(), cacheDir }).tuneRoundCalls).toBe(0);
    const changed = planLab({ dataDir: o.dataDir, labelFiles: [o.labels], armConfig: withWording(productConfig(), "New"), cacheDir });
    expect(changed.tuneRoundCalls).toBe(7);
    expect(changed.lines.join("\n")).toContain("changed wording: every window and frame-change judgment of it is new");
  });
});
