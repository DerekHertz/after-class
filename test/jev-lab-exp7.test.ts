const FRAME_P: Record<number, number> = { 1: 0.9, 2: 0.05, 3: 0.9 };
/** Records which questions were asked. Lesson framing is high with new concept high and stopping point low, so only the exp7 routing closes. */
function scriptedJev(asked: Set<string> = new Set()): JevClient {
  return {
    async ask<Q extends string>(req: JevRequest<Q>) {
      for (const k of Object.keys(req.questions)) asked.add(k);
      const answers: Record<string, JevAnswer> = {};
      if ("new_concept" in req.questions) {
        const text = (req.state as { passage: { text: string }[] }).passage.map((p) => p.text).join(" ");
        const top = text.includes("NEWTOPIC");
        answers.new_concept = { type: "noul", p: top ? 0.95 : 0.1 };
        answers.stopping_point = { type: "noul", p: top ? 0.1 : 0.1 };
        if ("lesson_framing" in req.questions) answers.lesson_framing = { type: "noul", p: top ? 0.9 : 0.1 };
      } else if ("refers_to_frame" in req.questions) answers.refers_to_frame = { type: "noul", p: req.images[0]!.bytes.at(-1) === 3 ? 0.1 : 0.9 };
      else answers.teaching_change = { type: "noul", p: FRAME_P[req.images[1]!.bytes.at(-1)!] ?? 0.9 };
      return { answers: answers as Record<Q, JevAnswer>, usage: { model: req.model, inputTokens: 100, outputTokens: 5, cacheReadTokens: null, cost: { kind: "unknown", reason: "fake" } } };
    },
  };
}

type Harness = Awaited<ReturnType<typeof harness>>;
async function harness() {
  const { dir: dataDir, captureId } = makeCapture();
  const labDir = tmp("lab");
  const ledger = join(labDir, "exp7");
  mkdirSync(ledger, { recursive: true });
  const labelFile = writeLabels(tmp("labels"), captureId);
  let t = 0;
  const asked = new Set<string>();
  const run = (over: Partial<RunOptions> & { phase: "tune" | "score" }): Promise<{ resultsPath: string; reportPath: string }> =>
    runLab({ dataDir, labDir, labelFiles: [labelFile], live: false, client: scriptedJev(asked), now: () => (t += 5), retryDelayMs: () => 0, out: () => {}, ...over });
  const base = await run({ phase: "tune" });
  const score = await run({ phase: "score" });
  return { dataDir, labDir, ledger, labelFile, captureId, run, asked, baseTune: base.resultsPath, baseScoreReport: score.reportPath };
}
