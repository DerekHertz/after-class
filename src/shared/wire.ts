/**
 * Wire schemas (zod 4). The only place JSON from another process is trusted
 * into domain types. Routes call `parse*`; nothing past a route sees `unknown`.
 * Domain modules never import this file (test/boundaries.test.ts).
 *
 * Extension → backend:  POST /ingest  { captureId, facts }  →  IngestAck
 * App → backend:        request bodies below; tutor turns stream NDJSON TutorStreamEvent.
 */
import { z } from "zod";
import { FRAME_BOUNDS } from "./domain";
import type {
  CaptureFact, CaptureView, InviteAnswer, InviteState, LearnerAct, LinkDecision, ObservationStatus, StartChoice, TurnEvent,
} from "./domain";
import { parseId } from "./ids";
import type { CaptureId, EvidenceId, Id, IdKind, ReviewId, TurnId } from "./ids";
import { Material, media } from "./time";

export class BadRequest extends Error {
  override readonly name = "BadRequest";
}

function idOf<K extends IdKind>(kind: K) {
  return z
    .string()
    .refine((s) => parseId(kind, s) !== null, `expected a ${kind}_ id`)
    .transform((s) => s as Id<K>);
}

const mediaS = z.number().nonnegative().transform(media);
const videoId = z.string().regex(/^[\w-]{11}$/);
const framePx = z.number().int().min(FRAME_BOUNDS.minShortSide).max(FRAME_BOUNDS.maxLongSide);

const factBase = z.object({ clientSeq: z.number().int().nonnegative(), wallMs: z.number() });

const wireFact = z.discriminatedUnion("kind", [
  factBase.extend({
    kind: z.literal("control"),
    action: z.enum(["start", "pause", "resume", "stop"]),
    reason: z.enum(["user", "left_watch_page", "returned_to_watch_page", "tab_closed"]),
  }),
  factBase.extend({
    kind: z.literal("source"), videoId, title: z.string().max(1000), channelName: z.string().max(1000),
    url: z.url(), durationS: z.number().positive().nullable(),
  }),
  factBase.extend({
    kind: z.literal("transcript"), videoId, origin: z.enum(["panel", "caption_intercept", "asr"]),
    language: z.string().max(64), autoGenerated: z.boolean(),
    segments: z
      .array(z.object({ start: mediaS, end: mediaS, text: z.string().max(10_000) }).refine((s) => s.end > s.start, "segment end must exceed start"))
      .max(20_000),
  }),
  factBase.extend({
    kind: z.literal("transcript_unavailable"), videoId,
    reason: z.enum(["no_captions", "panel_missing", "unusable", "intercept_failed"]),
  }),
  factBase
    .extend({
      kind: z.literal("span"), videoId, start: mediaS, end: mediaS, rate: z.number().positive().max(16),
      tabVisible: z.boolean(), wallDurationMs: z.number().int().nonnegative(),
    })
    .refine((s) => s.end > s.start, "span end must exceed start"),
  factBase.extend({
    kind: z.literal("ad"), videoId, atContentS: mediaS, wallDurationMs: z.number().int().nonnegative(),
    signals: z.tuple([z.enum(["dom_class", "duration_mismatch"])], z.enum(["dom_class", "duration_mismatch"])),
  }),
  factBase
    .extend({
      kind: z.literal("frame"), videoId, frameId: z.string().min(1).max(64), mediaS,
      width: framePx, height: framePx,
      trigger: z.enum(["change_settled", "keyframe", "first"]), diff: z.number(),
      jpegBase64: z.string().min(1).max(8 * 1024 * 1024),
    }),
  factBase.extend({
    kind: z.literal("channel"), channel: z.enum(["transcript", "frames", "playback"]),
    health: z.enum(["ok", "failed", "stalled"]), videoId: videoId.nullable(), atMediaS: mediaS.nullable(),
    detail: z.string().max(500),
  }),
  factBase.extend({
    kind: z.literal("transcription_choice"), videoId, choice: z.enum(["accept_asr", "continue_with_gap"]),
  }),
]);

export const ingestBatch = z.object({ captureId: idOf("cap"), facts: z.array(wireFact).max(500) });

/** Backend → extension, piggybacked on every ingest response (the MV3 worker has no push channel). */
export type IngestAck = {
  readonly ackedThroughSeq: number; // highest contiguous clientSeq stored
  readonly invite: InviteState;
  readonly capture: CaptureView;
  readonly reviewAppUrl: string;
};

function parseWith<S extends z.ZodType>(schema: S, raw: unknown): z.output<S> {
  const r = schema.safeParse(raw);
  if (!r.success) throw new BadRequest(z.prettifyError(r.error));
  return r.data;
}

export function parseIngestBatch(raw: unknown): { readonly captureId: CaptureId; readonly facts: readonly CaptureFact[] } {
  const batch = parseWith(ingestBatch, raw);
  const facts: CaptureFact[] = batch.facts.map((f) => ({ ...f, captureId: batch.captureId }));
  return { captureId: batch.captureId, facts };
}

