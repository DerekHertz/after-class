const jpeg = (tag: number) => Buffer.from([0xff, 0xd8, 0xff, 0xc0, 0x00, 0x11, 0x08, 0x01, 0x68, 0x02, 0x80, ...new Array<number>(8).fill(0), tag]);

function makeCapture(): { dir: string; captureId: CaptureId } {
  const dir = tmp("capture");
  const db = openDb(join(dir, "afterclass.sqlite"));
  const keyOf = (input: { readonly after: { readonly frame: { readonly id: string } } }): MemoKey => stableId("key", "frame_change", "test", input.after.frame.id);
  const evidence = createEvidence(db, dir, { lookupFrameChange: (i) => ({ kind: "missing", key: keyOf(i) }), runFrameChange: async () => undefined, frameChangeKey: keyOf, onChange: () => {} });
  const captureId = randomId("cap");
  const bodies: CaptureFactBody[] = [{ kind: "control", action: "start", reason: "user" }];
  for (const c of CLIPS) {
    const segments = [];
    for (let t = 0; t < LEN; t += 10) segments.push({ start: media(t), end: media(t + 10), text: `${t === 0 ? "NEWTOPIC " : ""}the lecturer discusses ${c.topic} in detail at second ${t} of this part` });
    bodies.push(
      { kind: "source", videoId: c.videoId, title: c.title, channelName: "Prof", url: `https://www.youtube.com/watch?v=${c.videoId}`, durationS: LEN },
      { kind: "transcript", videoId: c.videoId, origin: "panel", language: "en", autoGenerated: false, segments },
      { kind: "span", videoId: c.videoId, start: media(0), end: media(LEN), rate: 1, tabVisible: true, wallDurationMs: LEN * 1000 },
      ...[10, 20, 45].map((at, i): CaptureFactBody => ({ kind: "frame", videoId: c.videoId, frameId: `${c.videoId}-f${at}`, mediaS: media(at), width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: jpeg(c.frameTags[i]!).toString("base64") })),
    );
  }
  bodies.push({ kind: "control", action: "stop", reason: "user" });
  evidence.ingest({ captureId, facts: bodies.map((b, i) => ({ captureId, clientSeq: i, wallMs: 1000 + i, ...b }) as CaptureFact) });
  db.close();
  return { dir, captureId };
}

const FRAME_P: Record<number, number> = { 1: 0.9, 2: 0.05, 3: 0.9 };
function scriptedJev(): JevClient {
  return {
    async ask<Q extends string>(req: JevRequest<Q>) {
      const answers: Record<string, JevAnswer> = {};
      if ("new_concept" in req.questions) {
        const text = (req.state as { passage: { text: string }[] }).passage.map((p) => p.text).join(" ");
        const p = text.includes("NEWTOPIC") ? 0.95 : 0.1;
        answers.new_concept = { type: "noul", p };
        answers.stopping_point = { type: "noul", p };
      } else answers.teaching_change = { type: "noul", p: FRAME_P[req.images[1]!.bytes.at(-1)!] ?? 0.9 };
      return { answers: answers as Record<Q, JevAnswer>, usage: { model: req.model, inputTokens: 100, outputTokens: 5, cacheReadTokens: null, cost: { kind: "unknown", reason: "fake" } } };
    },
  };
}

const at30 = (videoId: string, extra: Record<string, unknown> = {}) => ({ videoId, mediaS: 30, note: "", confirmed: true, ...extra });
