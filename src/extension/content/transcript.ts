/**
 * Transcript acquisition (W2). Panel first, player caption interception second
 * (stack decision). Both produce ONE fact: the whole transcript as source text.
 * Clipping to watched intervals happens in the backend, so this module never
 * needs to know what was watched.
 *
 * Everything that parses is pure and unit-tested against fixtures. Every YouTube
 * selector lives in SELECTORS and is UNVERIFIED until the Windows Chrome probe.
 */
import type { CaptureFactBody, TranscriptOrigin, TranscriptSegment } from "../../shared/domain";
import { media } from "../../shared/time";

export type TranscriptResult =
  | Extract<CaptureFactBody, { kind: "transcript" }>
  | Extract<CaptureFactBody, { kind: "transcript_unavailable" }>;

export const SELECTORS = {
  panel: 'ytd-engagement-panel-section-list-renderer[target-id="engagement-panel-searchable-transcript"]',
  row: "ytd-transcript-segment-renderer, transcript-segment-view-model",
  showTranscriptButton: "ytd-video-description-transcript-section-renderer button",
  descriptionExpand: "#description-inline-expander #expand, ytd-text-inline-expander #expand, tp-yt-paper-button#expand",
  panelClose: '#visibility-button button, button[aria-label="Close transcript"]',
  expandedAttr: "visibility",
  expandedValue: "ENGAGEMENT_PANEL_VISIBILITY_EXPANDED",
} as const;

const ROW_TAGS = ["ytd-transcript-segment-renderer", "transcript-segment-view-model"] as const;
const MIN_SEGMENTS = 5;
const MIN_COVERAGE = 0.5;
const MAX_CUE_SHARE = 0.5;
const SETTLE_MAX_MS = 10_000;
const ACQUIRE_DEADLINE_MS = 30_000;
const CUE = /^(?:\[[^\]]*\]|\([^)]*\)|♪[^♪]*♪?|♫[^♫]*♫?)$/;

// ───────────────────────────── Pure parsing ─────────────────────────────────

const NAMED_ENTITIES: Readonly<Record<string, string>> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };

export function decodeEntities(s: string): string {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, body: string) => {
    if (body.startsWith("#")) {
      const code = body[1] === "x" || body[1] === "X" ? parseInt(body.slice(2), 16) : parseInt(body.slice(1), 10);
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
    }
    return NAMED_ENTITIES[body.toLowerCase()] ?? whole;
  });
}

/** Whitespace only. json3 text is plain, so "x < y" must survive. */
export function collapseWhitespace(s: string): string {
  return s.replace(/[​-‍﻿]/g, "").replace(/\s+/g, " ").trim();
}

/** Serialized HTML text to plain text. */
export function normalizeText(s: string): string {
  return collapseWhitespace(decodeEntities(s.replace(/<[^>]*>/g, " ")));
}

/** "1:02:03" → 3723, "2:05" → 125, "7" → 7. Anything else is null. */
export function parseClock(s: string): number | null {
  const m = s.trim().match(/^(?:(\d+):)?(\d{1,2}):(\d{2})$|^(\d+)$/);
  if (!m) return null;
  if (m[4] !== undefined) return Number(m[4]);
  return Number(m[1] ?? 0) * 3600 + Number(m[2]) * 60 + Number(m[3]);
}

/** "English (auto-generated)" → { language: "English", autoGenerated: true }. */
export function parseLanguageLabel(label: string): { readonly language: string; readonly autoGenerated: boolean } {
  const text = normalizeText(label);
  const language = text.replace(/\s*\([^)]*\)\s*/g, " ").trim();
  return { language: language === "" ? "unknown" : language.slice(0, 64), autoGenerated: /auto-?generated|automatically generated/i.test(text) };
}

export type PanelRow = { readonly timestamp: string; readonly text: string };

type OpenTag = { readonly name: string; readonly attrs: string; readonly end: number };

function classTokens(attrs: string): string[] {
  return (attrs.match(/\bclass\s*=\s*"([^"]*)"/i)?.[1] ?? "").split(/\s+/).filter(Boolean);
}

function* openTags(html: string): Generator<OpenTag> {
  for (const m of html.matchAll(/<([a-z][\w-]*)\b([^>]*)>/gi)) {
    if (!m[2]!.endsWith("/")) yield { name: m[1]!.toLowerCase(), attrs: m[2]!, end: m.index! + m[0].length };
  }
}

/** Inner HTML up to the matching close tag, counting nested tags of the same name. */
function innerHtml(html: string, tag: OpenTag): string {
  const re = new RegExp(`<(/?)${tag.name}\\b[^>]*>`, "gi");
  re.lastIndex = tag.end;
  let depth = 1;
  for (let m = re.exec(html); m; m = re.exec(html)) {
    depth += m[1] === "/" ? -1 : 1;
    if (depth === 0) return html.slice(tag.end, m.index);
  }
  return html.slice(tag.end);
}

function textOfFirst(html: string, match: (tag: OpenTag) => boolean): string | null {
  for (const tag of openTags(html)) if (match(tag)) return normalizeText(innerHtml(html, tag));
  return null;
}

const isTimestamp = (t: OpenTag) => classTokens(t.attrs).some((c) => c === "segment-timestamp" || c === "ytwTranscriptSegmentViewModelTimestamp");
const isSegmentText = (t: OpenTag) => classTokens(t.attrs).some((c) => c === "segment-text" || c === "yt-core-attributed-string");

/** Reads every transcript row out of the panel's serialized HTML (old and new YouTube markup). */
export function rowsFromHtml(html: string): PanelRow[] {
  const rows: PanelRow[] = [];
  const re = new RegExp(`<(${ROW_TAGS.join("|")})\\b[^>]*>([\\s\\S]*?)</\\1>`, "gi");
  for (const m of html.matchAll(re)) {
    const block = m[2]!;
    const timestamp = textOfFirst(block, isTimestamp);
    const text = textOfFirst(block, isSegmentText);
    if (timestamp !== null && text) rows.push({ timestamp, text });
  }
  return rows;
}

/** The footer's selected-language label, when present. */
export function languageFromPanelHtml(html: string): { readonly language: string; readonly autoGenerated: boolean } {
  const footer = html.match(/<ytd-transcript-footer-renderer\b[\s\S]*?<\/ytd-transcript-footer-renderer>/i)?.[0] ?? "";
  const label = textOfFirst(footer, (t) => /\bid\s*=\s*"label-text"/i.test(t.attrs));
  return parseLanguageLabel(label ?? footer);
}

/**
 * A row's end is the next row's start. The last row ends at the video's end, or
 * five seconds on when the duration is unknown or not past it.
 */
export function segmentsFromRows(rows: readonly PanelRow[], durationS: number | null): TranscriptSegment[] {
  const timed = rows.flatMap((r) => {
    const start = parseClock(r.timestamp);
    const text = normalizeText(r.text);
    return start === null || text === "" ? [] : [{ start, text }];
  });
  return timed.map((row, i) => {
    const nextStart = timed.slice(i + 1).find((n) => n.start > row.start)?.start;
    const lastEnd = durationS !== null && durationS > row.start ? durationS : row.start + 5;
    return { start: media(row.start), end: media(nextStart ?? lastEnd), text: row.text };
  });
}

/** json3 `events[{tStartMs,dDurationMs,segs[{utf8}]}]` → segments. Pure; unit-tested. */
export function parseJson3(payload: unknown): TranscriptSegment[] {
  const events = (payload as { events?: unknown } | null)?.events;
  if (!Array.isArray(events)) return [];
  const timed = events.flatMap((e: unknown) => {
    const ev = e as { tStartMs?: unknown; dDurationMs?: unknown; segs?: unknown } | null;
    // Live-stream and pre-roll tracks carry negative starts; media() would throw on them and lose the whole track.
    if (!ev || typeof ev.tStartMs !== "number" || !Number.isFinite(ev.tStartMs) || ev.tStartMs < 0 || !Array.isArray(ev.segs)) return [];
    const text = collapseWhitespace(ev.segs.map((s: unknown) => (typeof (s as { utf8?: unknown })?.utf8 === "string" ? (s as { utf8: string }).utf8 : "")).join(""));
    if (text === "") return [];
    const dur = typeof ev.dDurationMs === "number" && Number.isFinite(ev.dDurationMs) && ev.dDurationMs > 0 ? ev.dDurationMs : 0;
    return [{ startMs: ev.tStartMs, durMs: dur, text }];
  });
  return timed.map((ev, i) => {
    const nextMs = timed.slice(i + 1).find((n) => n.startMs > ev.startMs)?.startMs;
    const ownEnd = ev.durMs > 0 ? ev.startMs + ev.durMs : undefined;
    const endMs = ownEnd !== undefined ? Math.min(ownEnd, nextMs ?? ownEnd) : (nextMs ?? ev.startMs + 1000);
    return { start: media(ev.startMs / 1000), end: media(endMs / 1000), text: ev.text };
  });
}

/** Pure: ≥ 5 segments, ≥ 50% of duration covered, not dominated by "[Music]"-style cues. */
export function isUsable(segments: readonly TranscriptSegment[], durationS: number | null): boolean {
  if (segments.length < MIN_SEGMENTS) return false;
  const cues = segments.filter((s) => CUE.test(s.text.trim())).length;
  if (cues / segments.length > MAX_CUE_SHARE) return false;
  if (durationS === null || durationS <= 0) return true;
  const sorted = [...segments].sort((a, b) => a.start - b.start);
  let covered = 0;
  let reach = 0;
  for (const s of sorted) {
    const from = Math.max(s.start, reach);
    if (s.end > from) covered += s.end - from;
    reach = Math.max(reach, s.end);
  }
  return covered / durationS >= MIN_COVERAGE;
}

export function buildTranscript(
  videoId: string,
  origin: TranscriptOrigin,
  label: { readonly language: string; readonly autoGenerated: boolean },
  segments: readonly TranscriptSegment[],
  durationS: number | null,
): TranscriptResult {
  if (!isUsable(segments, durationS)) return { kind: "transcript_unavailable", videoId, reason: "unusable" };
  return { kind: "transcript", videoId, origin, language: label.language, autoGenerated: label.autoGenerated, segments };
}

// ───────────────────────────── Panel (DOM) ──────────────────────────────────

const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));

async function waitFor<T>(probe: () => T | null | undefined | false, timeoutMs: number, everyMs = 200): Promise<T | null> {
  const deadline = Date.now() + timeoutMs;
  for (;;) {
    const v = probe();
    if (v) return v;
    if (Date.now() >= deadline) return null;
    await sleep(everyMs);
  }
}

function panelElement(): Element | null {
  return document.querySelector(SELECTORS.panel);
}

function panelIsOpen(): boolean {
  return panelElement()?.getAttribute(SELECTORS.expandedAttr) === SELECTORS.expandedValue;
}

function findShowTranscriptButton(): HTMLElement | null {
  const direct = document.querySelector<HTMLElement>(SELECTORS.showTranscriptButton);
  if (direct) return direct;
  const byLabel = [...document.querySelectorAll<HTMLElement>("button, ytd-menu-service-item-renderer, tp-yt-paper-item")].find((el) =>
    /^show transcript$/i.test((el.getAttribute("aria-label") ?? el.textContent ?? "").trim()),
  );
  return byLabel ?? null;
}

function closePanel(): void {
  panelElement()?.querySelector<HTMLElement>(SELECTORS.panelClose)?.click();
}

/**
 * Open the "Show transcript" engagement panel, read every segment row, then
 * restore the user's layout.
 */
export async function readTranscriptPanel(videoId: string, durationS: number | null): Promise<TranscriptResult> {
  const missing: TranscriptResult = { kind: "transcript_unavailable", videoId, reason: "panel_missing" };
  const wasOpen = panelIsOpen();
  if (!wasOpen) {
    let button = findShowTranscriptButton();
    if (!button) {
      document.querySelector<HTMLElement>(SELECTORS.descriptionExpand)?.click();
      button = await waitFor(findShowTranscriptButton, 1500);
    }
    if (!button) return missing;
    button.click();
  }

  const rowCount = () => panelElement()?.querySelectorAll(SELECTORS.row).length ?? 0;
  const appeared = await waitFor(() => rowCount() > 0, 8000);
  if (!appeared) {
    if (!wasOpen) closePanel();
    return missing;
  }
  // Rows load in batches; wait for the count to stop growing.
  let last = -1;
  const settleDeadline = Date.now() + SETTLE_MAX_MS;
  for (let stable = 0; stable < 2 && Date.now() < settleDeadline; ) {
    await sleep(300);
    const now = rowCount();
    stable = now === last ? stable + 1 : 0;
    last = now;
  }

  const html = panelElement()?.outerHTML ?? "";
  if (!wasOpen) closePanel();
  const segments = segmentsFromRows(rowsFromHtml(html), durationS);
  return buildTranscript(videoId, "panel", languageFromPanelHtml(html), segments, durationS);
}

// ───────────────────────────── Interception (isolated side) ─────────────────

/** What main-world.ts posts. `lang` is the track's language code, `asr` is true for auto-generated tracks. */
export type TimedTextMessage = {
  readonly source: "afterclass";
  readonly kind: "timedtext";
  readonly videoId: string;
  readonly lang: string;
  readonly asr: boolean;
  readonly payload: unknown;
};

export function isTimedTextMessage(data: unknown): data is TimedTextMessage {
  const d = data as Partial<TimedTextMessage> | null;
  return !!d && d.source === "afterclass" && d.kind === "timedtext" && typeof d.videoId === "string" && typeof d.lang === "string" && typeof d.asr === "boolean";
}

const captured = new Map<string, TimedTextMessage>();
const waiters = new Set<(videoId: string) => void>();
let tapListening = false;

/** Start collecting forwarded captions. Call early: the player may fetch them before anyone asks. */
export function startCaptionListener(): void {
  if (tapListening) return;
  tapListening = true;
  window.addEventListener("message", (e: MessageEvent) => {
    if (e.source !== window || e.origin !== window.location.origin || !isTimedTextMessage(e.data)) return;
    if (parseJson3(e.data.payload).length === 0) return;
    captured.set(e.data.videoId, e.data);
    for (const w of waiters) w(e.data.videoId);
  });
}

function fromCaptured(videoId: string, durationS: number | null): TranscriptResult {
  const msg = captured.get(videoId);
  if (!msg) return { kind: "transcript_unavailable", videoId, reason: "intercept_failed" };
  try {
    return buildTranscript(videoId, "caption_intercept", { language: msg.lang || "unknown", autoGenerated: msg.asr }, parseJson3(msg.payload), durationS);
  } catch {
    return { kind: "transcript_unavailable", videoId, reason: "intercept_failed" };
  }
}

/**
 * Fallback: json3 captions forwarded by main-world.ts. Millisecond timing, better
 * than the panel. Resolves when a payload for `videoId` is held or arrives, or
 * after `timeoutMs`. The player only fetches captions while CC is on.
 */
export function awaitInterceptedCaptions(videoId: string, timeoutMs: number, durationS: number | null = null): Promise<TranscriptResult> {
  startCaptionListener();
  if (captured.has(videoId)) return Promise.resolve(fromCaptured(videoId, durationS));
  return new Promise((resolve) => {
    const done = () => {
      clearTimeout(timer);
      waiters.delete(onCapture);
      resolve(fromCaptured(videoId, durationS));
    };
    const onCapture = (id: string) => {
      if (id === videoId) done();
    };
    const timer = setTimeout(done, timeoutMs);
    waiters.add(onCapture);
  });
}

/**
 * Panel first, then captions the player fetched. One result, never throws, and
 * never outlasts `deadlineMs`: the page is hostile territory, and a caller that
 * awaits this must always get an answer.
 */
export async function acquireTranscript(videoId: string, durationS: number | null, interceptWaitMs = 4000, deadlineMs = ACQUIRE_DEADLINE_MS): Promise<TranscriptResult> {
  const unavailable: TranscriptResult = { kind: "transcript_unavailable", videoId, reason: "panel_missing" };
  const work = (async (): Promise<TranscriptResult> => {
    const panel = await readTranscriptPanel(videoId, durationS).catch((): TranscriptResult => unavailable);
    if (panel.kind === "transcript") return panel;
    const tapped = await awaitInterceptedCaptions(videoId, interceptWaitMs, durationS).catch((): TranscriptResult => ({ kind: "transcript_unavailable", videoId, reason: "intercept_failed" }));
    if (tapped.kind === "transcript") return tapped;
    return panel.reason === "unusable" || tapped.reason === "unusable" ? { kind: "transcript_unavailable", videoId, reason: "unusable" } : tapped;
  })();
  let timer: ReturnType<typeof setTimeout> | undefined;
  const deadline = new Promise<TranscriptResult>((resolve) => {
    timer = setTimeout(() => resolve(unavailable), deadlineMs);
  });
  try {
    return await Promise.race([work.catch((): TranscriptResult => unavailable), deadline]);
  } finally {
    clearTimeout(timer);
  }
}
