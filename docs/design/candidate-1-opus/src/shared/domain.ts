// ───────────────────────────── Review ───────────────────────────────────────

export type PartialReason =
  | { kind: "capture_gap"; gap: Gap }
  | { kind: "stopped_early"; droppedClaims: number }
  | { kind: "unverified_claims"; count: number }
  | { kind: "chunks_still_preparing"; count: number };

/**
 * R7 IN THE TYPE: written once at start, readonly, no update API anywhere.
 * Usable claims during the review = currently-supported claims whose evidence
 * lies inside `material` (corrections can change claims inside it, never add
 * material).
 * R10 IN THE TYPE: `claimsAtStart` is NonEmpty.
 */
export type FrozenScope = {
  readonly chunkRevisions: NonEmpty<ChunkRevisionId>;
  readonly material: Material;
  readonly claimsAtStart: NonEmpty<ClaimId>;
  readonly partial: readonly PartialReason[];
  readonly frozenAtSeq: Seq;
};

export type ReviewOptions =
  | { kind: "ready"; scope: ScopePreview }
  | { kind: "processing"; readyNow: ScopePreview | null; pendingChunks: number; estimateS: number | null }
  | { kind: "nothing_to_review"; gaps: readonly Gap[]; unverified: readonly Claim[]; rewatch: readonly { sourceId: SourceId; interval: Interval }[] };

export type ScopePreview = { readonly chunkRevisions: NonEmpty<ChunkRevisionId>; readonly supportedClaims: number; readonly partial: readonly PartialReason[] };

/** "prepared_only": start on what's ready, other chunks keep preparing. "stop_early": cancel pending in-scope work first. */
export type StartChoice = "prepared_only" | "stop_early";

export type ReviewPhase = "active" | "paused" | "ended";
export type DetourState =
  | { kind: "none" }
  | { kind: "proposed"; turnId: TurnId; topic: string; needsResource: ResourceId | null }
  | { kind: "awaiting_resource"; resourceId: ResourceId; topic: string }
  | { kind: "active"; topic: string; acceptedTurnId: TurnId } // reachable ONLY from a learner detour_accept turn (R11)
  ;

/** What the learner can do. Each is one turn fact (owner: user). */
export type LearnerAct =
  | { kind: "answer"; text: string; modality: "speech" | "text" }
  | { kind: "skip" }
  | { kind: "dont_know" }
  | { kind: "hint_request" }
  | { kind: "explain_request" }
  | { kind: "dispute"; text: string }
  | { kind: "detour_accept" }
  | { kind: "detour_decline" }
  | { kind: "detour_wait" | "detour_continue_without_resource" }
  | { kind: "continue_past_target" | "wrap_up" }
  | { kind: "pause" | "resume" | "end" };

/** What the tutor can do. Code computes the allowed subset each turn. */
export type TutorMove =
  | { kind: "ask_main"; threadId: ThreadId; claimIds: NonEmpty<ClaimId>; question: string }
  | { kind: "ask_followup"; threadId: ThreadId; question: string }
  | { kind: "diagnose"; threadId: ThreadId; hypothesis: string; question: string; evidence: readonly EvidenceId[] }
  | { kind: "hint"; threadId: ThreadId; text: string }
  | { kind: "explain"; threadId: ThreadId; text: string; evidence: readonly EvidenceId[] }
  | { kind: "propose_detour"; topic: string; reason: string; needsResource: ResourceId | null }
  | { kind: "detour_step"; text: string }
  | { kind: "answer_dispute"; threadId: ThreadId; text: string; evidence: readonly EvidenceId[]; settled: boolean }
  | { kind: "disclose_correction"; correctionId: string; text: string; evidence: readonly EvidenceId[] }
  | { kind: "close_thread"; threadId: ThreadId }
  | { kind: "wrap_up"; text: string };

export type TutorMoveKind = TutorMove["kind"];

/** Help kinds: a help turn before the first substantive answer caps the thread at after_help (R12). Single list. */
export const HELP_MOVES = ["hint", "explain"] as const satisfies readonly TutorMoveKind[];

/** Append-only review log. `atMs` drives the soft target (active time only); evidence never uses it. */
type TurnBase = { readonly id: TurnId; readonly reviewId: ReviewId; readonly seq: Seq; readonly atMs: number };
export type Turn =
  | (TurnBase & { readonly actor: "learner"; readonly threadId: ThreadId | null; readonly act: LearnerAct })
  | (TurnBase & { readonly actor: "tutor"; readonly threadId: ThreadId | null; readonly move: TutorMove; readonly say: string })
  | (TurnBase & { readonly actor: "code"; readonly threadId: null; readonly notice: CodeNotice });

/** Turns code inserts on its own authority (not the tutor's). */
export type CodeNotice =
  | { kind: "soft_target_reached"; elapsedS: number }
  | { kind: "correction_pending"; correctionId: string; affectedClaims: readonly ClaimId[] }
  | { kind: "resource_ready"; resourceId: ResourceId };

export type ObservationStatus = "independent" | "partial" | "after_help" | "unresolved" | "not_assessed";

export type DisputeState =
  | { kind: "none" }
  | { kind: "open"; turnId: TurnId }
  | { kind: "unsettled" }
  /** Only the learner's resolveDispute command produces this (R14). */
  | { kind: "resolved_by_learner"; outcome: "learner_was_right" | "it_was_my_gap" };

/** Facts the clamp reads, derived from a thread's turns. */
export type ThreadFacts = {
  readonly threadId: ThreadId;
  readonly firstSubstantiveAnswerSeq: Seq | null;
  readonly firstHelpSeq: Seq | null;
  readonly endedBySkip: boolean;
  readonly saidDontKnowOnly: boolean;
  readonly learnerTurns: readonly TurnId[];
  readonly helpTurns: readonly TurnId[];
};

export type Observation = {
  readonly id: ObservationId; // stableId("obs", reviewId, threadId)
  readonly reviewId: ReviewId;
  readonly threadId: ThreadId;
  readonly claimIds: NonEmpty<ClaimId>;
  readonly conceptIds: readonly ConceptId[];
  readonly proposed: ObservationStatus; // from the tutor's wrap-up proposal
  readonly status: ObservationStatus; // DERIVED: clamp(learnerOverride ?? proposed, facts)
  readonly clampedFrom: ObservationStatus | null;
  readonly dispute: DisputeState;
  readonly corrections: readonly string[];
  readonly facts: ThreadFacts;
};

