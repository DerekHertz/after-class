/** Control start, source, a transcript of ten 10 s segments, one 100 s span, optionally two frames, then stop. */
export function fixture(o: { frames: boolean }): Record<string, unknown>[] {
  const body: Record<string, unknown>[] = [
    { kind: "control", action: "start", reason: "user" },
    { kind: "source", videoId: VIDEO, title: "Lecture", channelName: "Prof", url: `https://www.youtube.com/watch?v=${VIDEO}`, durationS: 600 },
    {
      kind: "transcript", videoId: VIDEO, origin: "panel", language: "en", autoGenerated: false,
      segments: Array.from({ length: 10 }, (_, i) => ({ start: i * 10, end: i * 10 + 10, text: `Statement ${i + 1} about the topic.` })),
    },
    { kind: "span", videoId: VIDEO, start: 0, end: 100, rate: 1, tabVisible: true, wallDurationMs: 100_000 },
    ...(o.frames
      ? [5, 50].map((mediaS, i) => ({
          kind: "frame", videoId: VIDEO, frameId: `f${i}`, mediaS, width: 640, height: 360, trigger: "change_settled", diff: 0.4, jpegBase64: JPEG.toString("base64"),
        }))
      : []),
    { kind: "control", action: "stop", reason: "user" },
  ];
  return body.map((f, clientSeq) => ({ ...f, clientSeq, wallMs: 1000 + clientSeq }));
}

export const authed = (token: string) => ({ Authorization: `Bearer ${token}`, "Content-Type": "application/json" });

/** The learner's Wait, which asks for the lecture's review, so its preparation runs (flow C, 2026-11-18). Asking again changes nothing. */
export async function ask(b: Boot, captureId: CaptureId = CAP) {
  const res = await fetch(`${b.base}/captures/${captureId}/invite`, { method: "POST", headers: authed(b.r.token), body: JSON.stringify({ answer: "wait" }) });
  expect(res.status).toBe(200);
}

/** Posts facts as the extension does, and asks for nothing. */
export async function upload(b: Boot, facts: unknown[]) {
  const res = await fetch(`${b.base}/ingest`, { method: "POST", headers: authed(b.r.token), body: JSON.stringify({ captureId: CAP, facts }) });
  expect(res.status).toBe(200);
  return ingestAckResponse.parse(await res.json());
}

export async function ingest(b: Boot, facts: unknown[]) {
  const ack = await upload(b, facts);
  await ask(b);
  return ack;
}

/** The review the backend started on its own from the lecture's ask, once it exists (flow C, 2026-11-18). */
export async function askedReview(b: Boot): Promise<ReviewId> {
  let reviewId: ReviewId | null = null;
  await until(() => {
    const ask = b.r.modules.reviews.options(CAP).ask;
    reviewId = ask?.state === "started" ? ask.reviewId : null;
    return reviewId !== null;
  });
  return reviewId!;
}

